//! The egui editor — the nice-plug-egui glue only.
//!
//! This module owns the window: its size, its repaint cadence, and the handles
//! it draws from. Everything *computable* about the grid belongs in
//! `grid_math.rs` and everything about the look in `theme.rs`, so that the
//! parts worth testing can be tested without a display.
//!
//! The editor is a reader, not an owner: it holds the same `Arc<SeqModel>`,
//! `Arc<Playhead>` and `Arc<BitstepParams>` the audio thread uses, so a GUI
//! edit and the next block see one sequence. Writes go back through
//! `SeqModel`'s setters (value edits) and writer methods (shape edits), and
//! parameter changes through [`GuiContext`]'s setter — never by mutating a
//! copy.

