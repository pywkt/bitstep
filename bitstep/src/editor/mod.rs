/// What the primary button does on the step grid.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum EditMode {
    /// Click toggles, horizontal drag paints, vertical drag sets velocity.
    Steps,
    /// Drag draws pitch: up/down sets the height, sideways carries it across
    /// steps, Shift draws a straight slope, and a click resets a step to 0.
    Pitch,
}

impl EditMode {
    const ALL: [EditMode; grid_math::MODE_BUTTONS] = [EditMode::Steps, EditMode::Pitch];

    fn label(self) -> &'static str {
        match self {
            EditMode::Steps => "Steps",
            EditMode::Pitch => "Pitch",
        }
    }

    fn hover(self) -> &'static str {
        match self {
            EditMode::Steps => {
                "Click and drag to turn steps on and off; drag up or down for velocity"
            }
            EditMode::Pitch => {
                "Drag up or down to set pitch and sideways to draw across steps. \
                 Hold Shift for a straight slope. Click a step to reset it."
            }
        }
    }
}

/// The cell a pan/ratchet/probability popover is open on.
///
/// By lane *id* and pattern index rather than by row, for [`StepPaint`]'s
/// reason and the pattern's equivalent: the popover outlives the frame it was
/// opened in, and a lane reordered or removed under it — or a `patsel` change
/// swapping the grid for another pattern — must not leave three sliders
/// pointed at a step nobody asked about. Either makes the lookup fail, and
/// the popover closes instead.
#[derive(Clone, Copy)]
struct StepPopover {
    lane_id: u32,
    pattern: usize,
    step: usize,
    /// The corner of the cell the popover hangs under, in screen points.
    ///
    /// Latched at the press rather than recomputed from the cell each frame:
    /// the grid scrolls (follow mode moves it on its own), and a popover that
    /// slid along with the cell — or off the window with it — would be
    /// impossible to use. A context menu stays where it was opened.
    at: Pos2,
}

/// Wheel scroll banked against one lane's key, in points.
///
/// egui spreads one wheel notch over several frames of `smooth_scroll_delta`,
/// so the points are added up until they are worth a semitone
/// ([`grid_math::take_scroll_steps`]) rather than each frame of a notch
/// moving the key. Which lane they belong to is part of the state: moving the
/// pointer to another lane's key must not spend what the first one banked.
struct KeyScroll {
    lane_id: u32,
    points: f32,
}

/// A lane-reorder drag in progress.
///
/// The machine is [`LaneReorder`]; what the editor adds is the lane's id, for
/// [`StepPaint`]'s reason in its sharpest form: this gesture *moves* lanes
/// between rows, so a position is meaningless without saying whose it is.
/// With the id latched, a lane removed mid-drag (a state load) simply stops
/// being moved.
struct LaneDrag {
    lane_id: u32,
    drag: LaneReorder,
}

/// The name being typed into one lane's rename field.
///
/// By lane id, like every other gesture here: a context menu outlives the
/// frame it was opened in, and a buffer left pointing at a reordered or
/// removed lane must not rename a stranger. A mismatch refills the buffer
/// from the lane whose menu is open now.
struct LaneRename {
    lane_id: u32,
    text: String,
}

/// A lane name being typed in place: a double-click on the name swaps it
/// for a text field holding the whole name, selected, so typing replaces it.
///
/// Unlike the menu's field ([`LaneRename`]), nothing is written while the
/// user types: Enter or leaving the field (a click elsewhere, Tab, the row
/// scrolling away) saves the name, and Escape puts the old one back — which
/// needs the old one untouched until then. By lane id, like every gesture.
struct NameEdit {
    lane_id: u32,
    text: String,
    /// Set until the field has been drawn once: that frame gives it the
    /// keyboard and selects the whole name.
    opening: bool,
    /// Whether this frame drew the field. A row scrolled out of view is not
    /// drawn, its field loses the keyboard with it, and that counts as
    /// leaving the field.
    shown: bool,
}

/// How an in-place name edit ended ([`name_field`]).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum NameEditEnd {
    /// Enter, or the field lost the keyboard: keep what was typed.
    Save,
    /// Escape: keep the name the lane had.
    Cancel,
}

/// A menu item that destroys data irreversibly, and so is clicked twice
/// ([`LaneConfirm`]).
///
/// Only these two: a lane deleted takes its steps in all eight patterns with
/// it, and a lane cleared loses every value the user drew in the pattern on
/// screen — and nothing in the plugin can bring either back, because
/// `SeqModel` keeps no history and a host's undo does not reach plugin state.
///
/// The other three bulk edits are *not* here, and the difference is whether a
/// second click undoes the first: `invert` switches a lane straight back,
/// `nudge` rotates back the other way, and `randomise` is the roll-again
/// gesture it would be wrong to put two clicks in the way of. They are
/// destructive in scope but not irreversible, so a confirmation would only
/// make them tiring.
#[derive(Clone, Copy, Eq, PartialEq)]
enum LaneAction {
    Delete,
    Clear,
}

impl LaneAction {
    /// What the item says before it is armed.
    fn label(self) -> &'static str {
        match self {
            LaneAction::Delete => "delete",
            LaneAction::Clear => "clear",
        }
    }

    /// What it says once a click has armed it, and what the hover explains.
    fn armed_label(self) -> &'static str {
        match self {
            LaneAction::Delete => "delete — click again",
            LaneAction::Clear => "clear — click again",
        }
    }

    fn warning(self) -> &'static str {
        match self {
            LaneAction::Delete => {
                "Removes the lane and its steps in every pattern. Ctrl+Z brings it back."
            }
            LaneAction::Clear => {
                "Wipes every step of this lane in the pattern on screen. Ctrl+Z undoes it."
            }
        }
    }
}

/// The destructive menu item one lane has armed, waiting for its second
/// click.
///
/// By lane id for [`LaneRename`]'s reason, and one at a time on purpose:
/// arming either item disarms the other, so there is never more than one
/// click standing between the user and a loss. It is dropped the moment the
/// menu holding it closes — an arm is only as good as the menu it was made
/// in.
struct LaneConfirm {
    lane_id: u32,
    action: LaneAction,
}

/// A copy of one pattern over another, from the pattern button menu.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
struct PatternCopy {
    from: usize,
    to: usize,
}

/// Where one lane's header sits in the list this frame.
///
/// The band and the row are what the row is drawn and addressed by; the row
/// count and the row pitch are what a reorder drag measures in
/// ([`LaneReorder`]), and they come from the same [`GridView`] the cells are
/// drawn through so that a dragged lane lands on the row it looks like it
/// will.
#[derive(Clone, Copy)]
struct HeaderPlace {
    band: Rect,
    row: usize,
    pitch: f32,
    /// Screen `y` of the top of row 0, scrolled: what turns a pointer's
    /// screen `y` into the content `y` a [`LaneReorder`] measures in.
    content_top: f32,
    /// Whether this is the lane the parameter panel is editing, which the
    /// header marks.
    selected: bool,
}

/// What the primary button being down on the step strip currently means.
///
/// The step strip puts three gestures on one button — "click toggles;
/// horizontal drag paints the entered on/off value; vertical drag on an
/// on-step edits velocity" — and only the press's cell tells them apart in
/// advance. A press on an *off* step can only be the first two, which are the
/// same machine ([`PaintDrag`]), so it draws straight away. A press on an
/// *on* step could still become any of the three, so it waits in
/// [`Gesture::Pending`] until the pointer has moved far enough to say which
/// (or come up, which makes it the click).
///
/// A press on a lane's end handle is none of the three: it is the length drag
/// of the lane's loop, which the handle's own hit region tells apart in
/// advance.
enum Gesture {
    /// A press on an on step, not yet resolved. Nothing has been written.
    Pending(PendingPress),
    /// An on/off paint drag, which the press has already written its first
    /// cell of.
    Paint(StepPaint),
    /// A velocity drag on the step the press landed on.
    Velocity(StepVelocity),
    /// A drag of the handle after a lane's last step, which edits its loop
    /// length.
    Length(LaneLength),
    /// Drawing pitch, in pitch mode.
    Pitch(StepPitch),
}

/// A pitch-drawing gesture the editor is in the middle of. By lane id for
/// [`StepPaint`]'s reason; the press position is kept for the deadzone that
/// tells a click (reset) from a drag (draw).
struct StepPitch {
    lane_id: u32,
    origin: Pos2,
    drag: PitchDraw,
}

/// A press on an on step, waiting to find out what it is.
///
/// Deferring the edit is what makes a velocity drag possible at all: writing
/// the toggle on the press, as a press on an off step does, would switch the
/// step off before the gesture that wants to edit its velocity had started.
/// The cost is that an erase lands on the release rather than the press, which
/// is how a step sequencer's eraser is expected to behave anyway.
#[derive(Clone, Copy)]
struct PendingPress {
    lane_id: u32,
    row: usize,
    step: usize,
    /// Where the button went down: the origin both decisions measure from.
    origin: Pos2,
    /// The velocity the step had then — a velocity drag's zero point, latched
    /// here so that the gesture's own writes cannot move it.
    velocity: u8,
}

/// A velocity drag the editor is in the middle of.
///
/// As with [`StepPaint`], the lane's id rather than its row: the machine
/// ([`VelocityDrag`]) knows which row was under the pointer, the model
/// addresses lanes by id, and latching the id means a lane reordered
/// mid-gesture takes its edits with it instead of handing them to a
/// neighbour.
struct StepVelocity {
    lane_id: u32,
    drag: VelocityDrag,
}

/// A paint drag the editor is in the middle of.
///
/// The machine is [`PaintDrag`]; what the editor adds is *who* is being
/// written to. The lane's id is latched at the press because `SeqModel`
/// addresses lanes by id while the grid only knows rows: a lane removed or
/// reordered mid-gesture (by a state load, say) must not hand the rest of the
/// drag to whichever lane slid into that row — with the id, the writes simply
/// stop landing.
struct StepPaint {
    lane_id: u32,
    drag: PaintDrag,
}

/// An end-handle drag the editor is in the middle of.
///
/// The machine is [`EndHandleDrag`]; as with [`StepPaint`] what the editor
/// adds is the lane's id, so that a lane reordered mid-gesture keeps its own
/// length rather than handing the rest of the drag to a neighbour.
struct LaneLength {
    lane_id: u32,
    drag: EndHandleDrag,
}

impl BitstepEditor {
    /// Shares the plugin's handles; takes no copies of anything.
    pub fn new(
        params: Arc<BitstepParams>,
        model: Arc<SeqModel>,
        playhead: Arc<Playhead>,
    ) -> BitstepEditor {
        BitstepEditor {
            params,
            model,
            playhead,
            gui_context: None,
            gesture: None,
            gesture_pattern: 0,
            popover: None,
            key_scroll: None,
            lane_drag: None,
            rename: None,
            name_edit: None,
            confirm: None,
            pattern_copy: None,
            pattern_page: 0,
            paged_for: None,
            song_edit: None,
            song_scroll: 0.0,
            rng: Prng::new(clock_seed()),
            scroll: Vec2::ZERO,
            follow: true,
            mode: EditMode::Steps,
            selected_lane: None,
            panel_open: true,
            param: ParamKind::Velocity,
            param_draw: None,
            key_forwarder: None,
            key_forwarder_tried: false,
            repaint: RepaintNotifier::new(),
        }
    }

    /// The pattern the grid shows: the one `patsel` names, as an index into
    /// `SeqData::patterns`.
    ///
    /// The parameter is one-based, so this is the GUI's half of
    /// [`BlockCtx::pattern_index`] — the same offset against the same constant,
    /// never a literal `1`. [`BitstepParams::pattern_select`] has already
    /// clamped the value into range, and the saturating subtract means even a
    /// future range change cannot underflow this.
    fn shown_pattern(&self) -> usize {
        usize::from(self.params.pattern_select().saturating_sub(BlockCtx::PATTERN_SELECT_MIN))
    }

    /// Pointer handling for the step strip: a press on the cell under it
    /// toggles, paints or edits velocity, depending on where it lands and
    /// where it goes (see [`Gesture`]).
    ///
    /// [`Sense::drag`] alone, never `click_and_drag`: egui postpones deciding
    /// between a click and a drag until the pointer has moved far enough or
    /// been let go, and this is a grid of thousands of cells that has to know
    /// the moment the button goes down which one it went down on. The
    /// click-or-drag decision the grid does need is its own
    /// ([`grid_math::resolve_axis`]), because it has three outcomes rather
    /// than two.
    ///
    /// Only the primary button paints, and only unmodified: the secondary
    /// button and `Alt`+primary open the pan/ratchet/probability popover
    /// instead. Nothing is dragged by either, so the
    /// gesture machinery never sees them — which is also why `dragged_by` is
    /// asked about [`PointerButton::Primary`] by name rather than about any
    /// button at all.
    fn interact_steps(
        &mut self,
        ui: &mut egui::Ui,
        view: &GridView,
        data: &SeqData,
        pattern: usize,
    ) -> Option<GridHit> {
        let id = egui::Id::unique(STEP_STRIP_ID);
        let response = ui.interact(view.viewport(), id, Sense::drag());

        // The press comes from the pointer's own events, not from
        // `Response::drag_started`: egui does not count a press and a release
        // that arrive in the same frame as a drag *or* a click of a
        // drag-sensing widget (its `interaction.rs` says so outright), and at
        // this editor's 30 Hz a quick tap is exactly that — the toggle, the
        // strip's most basic gesture, would simply go missing.
        //
        // `hovered` is what makes the press ours: for a widget that senses
        // dragging it is true only when the pointer is on the topmost such
        // widget, so a press that egui routed to something drawn over the
        // strip is not taken for a press on the strip.
        if response.hovered()
            && let Some((pos, button, modifiers)) = ui.input(step_press)
        {
            // `Alt` on the primary button is the keyboard half of the
            // popover's two ways in (`Alt`+press or right-click): one gesture
            // for a mouse with two buttons and one for a trackpad without them.
            if button == PointerButton::Secondary || modifiers.alt {
                self.open_popover(view, data, pattern, pos);
            } else {
                self.gesture_pattern = pattern;
                self.begin_gesture(view, data, pattern, pos);
            }
        }
        // From here on, a gesture in progress edits the pattern it began in,
        // and only while that pattern is the one on screen.
        let shown = pattern;
        let pattern = if self.gesture.is_some() { self.gesture_pattern } else { pattern };

        // The handle is a resize grip, so it says so under the pointer —
        // both when it is merely hovered and for as long as a drag of it is
        // running, which is when the pointer has usually left it behind.
        let over_handle = response.hovered()
            && response.hover_pos().is_some_and(|pos| {
                matches!(
                    view.hit(pos, data.lane_count(), |row| row_length(data, pattern, row)),
                    Some(GridHit::EndHandle { .. })
                )
            });
        if over_handle || matches!(self.gesture, Some(Gesture::Length(_))) {
            ui.ctx().set_cursor_icon(CursorIcon::ResizeHorizontal);
        }

        if response.dragged_by(PointerButton::Primary) {
            // Includes the frame of the press itself, where the pointer has
            // not moved and there is nothing to decide yet.
            if pattern == shown
                && let Some(pos) = response.interact_pointer_pos()
            {
                let shift = ui.input(|input| input.modifiers.shift);
                self.continue_gesture(view, data, pattern, pos, shift);
            }
        } else {
            // Button up, pointer gone from the window, Escape pressed — every
            // way a gesture can end leaves `dragged()` false, so this is the
            // one place it has to be finished. Holding a stale one would let
            // the next press continue the old span; dropping a pending one
            // without finishing it would swallow the click's toggle.
            self.end_gesture(pattern);
        }

        // What a click would land on, for the hover outline: only while no
        // gesture is running (the gesture's own edits are its feedback) and
        // only when the strip itself is under the pointer, not a menu or
        // popover drawn over it.
        if self.gesture.is_some() || !response.hovered() {
            return None;
        }
        let pos = response.hover_pos()?;
        view.hit(pos, data.lane_count(), |row| row_length(data, shown, row))
    }

    /// A press landed on the strip: start the gesture its cell allows, and
    /// write the toggle straight away if that is the only thing the press can
    /// have meant.
    ///
    /// A press on the empty space past a short lane's last step starts
    /// nothing; one on a lane's end handle starts the length drag, which is
    /// the one gesture the press can tell apart on its own.
    fn begin_gesture(&mut self, view: &GridView, data: &SeqData, pattern: usize, pos: Pos2) {
        let hit = view.hit(pos, data.lane_count(), |row| row_length(data, pattern, row));
        let (row, step) = match hit {
            Some(GridHit::Cell { row, step }) => (row, step),
            Some(GridHit::EndHandle { row }) => {
                self.begin_length(view, data, pattern, row, pos);
                return;
            }
            None => return,
        };
        // Both exist for a row `hit` accepted; a row that somehow has no data
        // is dropped rather than unwrapped, as in `paint_steps`.
        let (Some(lane), Some(lane_data)) = (data.lane(row), data.lane_data(pattern, row)) else {
            return;
        };

        self.selected_lane = Some(lane.id);
        let current = lane_data.step(step);
        if self.mode == EditMode::Pitch {
            // Nothing written yet: a press that comes up without moving is the
            // reset click, and one that moves draws.
            let drag = PitchDraw::begin(row, step, current.pitch(), pos);
            self.gesture = Some(Gesture::Pitch(StepPitch { lane_id: lane.id, origin: pos, drag }));
            return;
        }
        if current.is_on() {
            // Could still be any of the three gestures, so nothing is written
            // until it is known which — see [`PendingPress`].
            self.gesture = Some(Gesture::Pending(PendingPress {
                lane_id: lane.id,
                row,
                step,
                origin: pos,
                velocity: current.velocity(),
            }));
            return;
        }

        // An off step has no velocity to drag, so the press can only draw.
        // That happens here, before anything has moved, so a plain click is
        // already a finished edit.
        let drag = PaintDrag::begin(row, step, false);
        self.write_steps(pattern, lane.id, &drag, step..step + 1);
        self.gesture = Some(Gesture::Paint(StepPaint { lane_id: lane.id, drag }));
    }

    /// The pointer moved with the button still down: resolve a pending press,
    /// then let the gesture it is have the position.
    fn continue_gesture(
        &mut self,
        view: &GridView,
        data: &SeqData,
        pattern: usize,
        pos: Pos2,
        shift: bool,
    ) {
        // Copied out of `self` so that the gesture's own methods can borrow
        // `self` again below.
        let pending = match self.gesture {
            Some(Gesture::Pending(press)) => press,
            Some(Gesture::Paint(_)) => {
                self.paint_to(view, data, pattern, pos);
                return;
            }
            Some(Gesture::Velocity(_)) => {
                self.drag_velocity(pattern, pos);
                return;
            }
            Some(Gesture::Length(_)) => {
                self.drag_length(data, pattern, pos);
                return;
            }
            Some(Gesture::Pitch(_)) => {
                self.draw_pitch(view, data, pattern, pos, shift);
                return;
            }
            None => return,
        };

        match grid_math::resolve_axis(pos - pending.origin) {
            // Inside the deadzone: still a click, still nothing written.
            DragAxis::Undecided => {}
            DragAxis::Vertical => {
                let drag = VelocityDrag::begin(
                    pending.row,
                    pending.step,
                    pending.velocity,
                    pending.origin.y,
                );
                self.gesture =
                    Some(Gesture::Velocity(StepVelocity { lane_id: pending.lane_id, drag }));
                // This frame's height already counts: the pointer has moved
                // past the deadzone, so the fill follows it from the first
                // frame of the drag.
                self.drag_velocity(pattern, pos);
            }
            DragAxis::Horizontal => {
                // The press's own cell was never written, so the erase starts
                // with it and then covers everything on the way to `pos`.
                let drag = PaintDrag::begin(pending.row, pending.step, true);
                self.write_steps(pattern, pending.lane_id, &drag, pending.step..pending.step + 1);
                self.gesture =
                    Some(Gesture::Paint(StepPaint { lane_id: pending.lane_id, drag }));
                self.paint_to(view, data, pattern, pos);
            }
        }
    }

    /// The button came up, or the gesture was taken away: write whatever the
    /// gesture still owes, and drop it.
    ///
    /// Only a [`Gesture::Pending`] owes anything. A press that came up without
    /// ever leaving the deadzone is the click that toggles a step, and
    /// since it landed on an on step the toggle it stands for is an erase.
    ///
    /// A pitch press that never left the deadzone is the pitch-mode click,
    /// which resets that step's pitch to 0.
    fn end_gesture(&mut self, pattern: usize) {
        match self.gesture.take() {
            Some(Gesture::Pending(press)) => {
                let drag = PaintDrag::begin(press.row, press.step, true);
                self.write_steps(pattern, press.lane_id, &drag, press.step..press.step + 1);
            }
            Some(Gesture::Pitch(pitch)) if !pitch.drag.moved() => {
                let step = pitch.drag.origin_step();
                self.model.update_step(pattern, pitch.lane_id, step, |step| step.with_pitch(0));
            }
            _ => {}
        }
    }

    /// Writes the pitches a running pitch drag's pointer means
    /// ([`PitchDraw::draw_to`]). Row-locked like a paint drag: the column
    /// under the pointer picks the step, clamped into the lane's length, so a
    /// stroke that overshoots either end still reaches the first or last step.
    fn draw_pitch(
        &mut self,
        view: &GridView,
        data: &SeqData,
        pattern: usize,
        pos: Pos2,
        shift: bool,
    ) {
        let Some(Gesture::Pitch(pitch)) = self.gesture.as_mut() else {
            return;
        };
        let row = pitch.drag.row();
        let Some(lane_data) = data.lane_data(pattern, row) else {
            return;
        };
        let length = (lane_data.length() as usize).min(lane_data.capacity());
        if length == 0 {
            return;
        }
        let last = length - 1;
        let step = match view.step_at(pos) {
            Some(step) => step.min(last),
            // Left of the first column.
            None if pos.x < view.viewport().center().x => 0,
            None => last,
        };
        let origin = pitch.origin;
        let writes = pitch.drag.draw_to(step, pos, origin, shift, |s| lane_data.step(s).pitch());
        let lane_id = pitch.lane_id;
        for (index, value) in writes {
            if index < length && lane_data.step(index).pitch() != value {
                self.model.update_step(pattern, lane_id, index, |step| step.with_pitch(value));
            }
        }
    }

    /// Paints every cell a running paint drag has newly entered.
    ///
    /// Row-locked and bounded by the row's *current* length — a drag past the
    /// last step, or into the lane above, paints nothing new rather than
    /// walking off the lane.
    fn paint_to(&mut self, view: &GridView, data: &SeqData, pattern: usize, pos: Pos2) {
        let Some(Gesture::Paint(paint)) = self.gesture.as_mut() else {
            return;
        };
        let row = paint.drag.row();
        let length = u64::from(row_length(data, pattern, row));
        let Some(step) = view.step_at(pos).filter(|step| (*step as u64) < length) else {
            return;
        };

        let fresh = paint.drag.enter(step);
        // Copied out so the borrow of `self.gesture` ends before the write.
        let (lane_id, drag) = (paint.lane_id, paint.drag);
        self.write_steps(pattern, lane_id, &drag, fresh);
    }

    /// Writes the velocity a running velocity drag's pointer height means.
    ///
    /// A value edit like the paint drag's, and quiet in the same way: a frame
    /// that did not move the velocity writes nothing
    /// ([`VelocityDrag::enter`]). Column-blind on purpose — the gesture owns
    /// one step, so only `pos.y` is read.
    fn drag_velocity(&mut self, pattern: usize, pos: Pos2) {
        let Some(Gesture::Velocity(velocity)) = self.gesture.as_mut() else {
            return;
        };
        let Some(target) = velocity.drag.enter(pos.y) else {
            return;
        };

        // Copied out so the borrow of `self.gesture` ends before the write.
        let (lane_id, drag) = (velocity.lane_id, velocity.drag);
        self.model.update_step(pattern, lane_id, drag.step(), |step| drag.apply(step, target));
    }

    /// A press landed on a lane's end handle: start the drag that edits its
    /// loop length.
    ///
    /// Nothing is written yet — a press that comes up without moving leaves
    /// the length exactly as it was, which is what grabbing a handle and
    /// letting go should do.
    fn begin_length(
        &mut self,
        view: &GridView,
        data: &SeqData,
        pattern: usize,
        row: usize,
        pos: Pos2,
    ) {
        let (Some(lane), Some(lane_data)) = (data.lane(row), data.lane_data(pattern, row)) else {
            return;
        };
        let drag =
            EndHandleDrag::begin(row, lane_data.length(), pos.x, view.metrics().step_pitch());
        self.gesture = Some(Gesture::Length(LaneLength { lane_id: lane.id, drag }));
    }

    /// Writes the loop length a running end-handle drag's pointer means.
    ///
    /// The same two writes the header's length field makes, for the same
    /// reason ([`LengthEdit`]): a length inside the lane's capacity is a value
    /// edit, and one past it is a grow followed by a value edit. Quiet on a
    /// frame that did not move the length ([`EndHandleDrag::enter`]), which
    /// matters here because a grow republishes the whole sequence.
    fn drag_length(&mut self, data: &SeqData, pattern: usize, pos: Pos2) {
        let Some(Gesture::Length(length)) = self.gesture.as_mut() else {
            return;
        };
        let Some(wanted) = length.drag.enter(pos.x) else {
            return;
        };

        // Copied out so the borrow of `self.gesture` ends before the writes.
        let (lane_id, row) = (length.lane_id, length.drag.row());
        // By row, as the header does: the capacity belongs to this frame's
        // data, and `ensure_capacity` only ever grows, so a lane that moved
        // out from under the gesture costs at most a chunk it did not need.
        let capacity = data.lane_data(pattern, row).map_or(0, LaneData::capacity);
        let edit = LengthEdit::resolve(f64::from(wanted), capacity);
        // A failed grow means the lane is gone, and then the length has
        // nowhere to go either — `set_length` would answer `false` as well.
        let grown =
            edit.grow().is_none_or(|steps| self.model.ensure_capacity(pattern, lane_id, steps));
        if grown {
            self.model.set_length(pattern, lane_id, edit.length());
        }
    }

    /// Writes the drag's latched value to `steps` of one lane.
    ///
    /// A value edit, so it goes through the model's step setter and no further:
    /// nothing about the sequence's shape changes, and the audio thread picks
    /// the new bits up on its next block without a republish. `update_step`
    /// returns `false` for a lane or index that has gone — the GUI may be a
    /// frame behind a removal — which needs no handling here beyond not writing
    /// it.
    fn write_steps(&self, pattern: usize, lane_id: u32, drag: &PaintDrag, steps: Range<usize>) {
        for index in steps {
            self.model.update_step(pattern, lane_id, index, |step| drag.apply(step));
        }
    }

    /// A secondary (or `Alt`+primary) press landed on the strip: open the
    /// pan/ratchet/probability popover on its cell.
    ///
    /// Only on a step that is **on**, for the reason the velocity drag is:
    /// the three fields are how a note sounds, and a step that does not sound
    /// has none to tune. It also keeps the popover honest about the grid —
    /// every value it can set has a marker ([`paint_markers`]) or a fill
    /// behind it, and an off step draws neither. A press anywhere else — the
    /// end handle, the space past a short lane, an empty step — closes
    /// whatever was open instead, which is what a click outside a context
    /// menu does.
    fn open_popover(&mut self, view: &GridView, data: &SeqData, pattern: usize, pos: Pos2) {
        self.popover = None;

        let hit = view.hit(pos, data.lane_count(), |row| row_length(data, pattern, row));
        let Some(GridHit::Cell { row, step }) = hit else {
            return;
        };
        // Both exist for a row `hit` accepted; a row that somehow has no data
        // is dropped rather than unwrapped, as in `paint_steps`.
        let (Some(lane), Some(lane_data)) = (data.lane(row), data.lane_data(pattern, row)) else {
            return;
        };
        self.selected_lane = Some(lane.id);
        if !lane_data.step(step).is_on() {
            return;
        }

        // Anchored to the cell rather than to the pointer, so the sliders hang
        // squarely under the step they belong to however the press was aimed.
        let at = view.cell_rect(row, step).left_bottom();
        self.popover = Some(StepPopover { lane_id: lane.id, pattern, step, at });
    }

    /// The pan/ratchet/probability popover, while one is open.
    ///
    /// Three sliders over one step, each writing straight through
    /// [`SeqModel`] as a value edit — there is no OK button and nothing is
    /// buffered, so the grid behind the popover shows every move of a rail as
    /// it happens: the state is the feedback.
    ///
    /// Closed by a click outside it or by `Escape` (egui's own doing, through
    /// [`PopupCloseBehavior::CloseOnClickOutside`]), and by the step it was
    /// opened on going away under it.
    fn ui_step_popover(&mut self, ui: &mut egui::Ui, data: &SeqData, pattern: usize) {
        let Some(popover) = self.popover else {
            return;
        };

        // Still the pattern it was opened on, still a lane with that id, still
        // a step inside that lane, and still on: anything else means the
        // sliders no longer point at what the user opened — a lane removed or
        // reordered, a state load, a `patsel` change, the step erased by a
        // paint drag — so the popover closes rather than editing a stranger.
        let found = (popover.pattern == pattern)
            .then(|| data.position_of(popover.lane_id))
            .flatten()
            .and_then(|row| data.lane(row).zip(data.lane_data(pattern, row)))
            .filter(|(_, lane_data)| {
                // Length, not capacity: a lane shortened past the step hides
                // it, and a popover on a hidden step edits something unseen.
                popover.step < (lane_data.length() as usize).min(lane_data.capacity())
                    && lane_data.step(popover.step).is_on()
            });
        let Some((lane, lane_data)) = found else {
            self.popover = None;
            return;
        };

        // A field borrow rather than `self.…` inside the closures below, as in
        // `ui_lane_header`: a `self` capture would borrow all of `self`, and
        // the close check at the end needs it back.
        let model = &self.model;
        // egui closes the popup by clearing this, which is what tells the
        // editor to forget which cell it belonged to.
        let mut open = true;
        // One id per target. egui remembers, per popup id, that a press
        // started while it was open; with a single shared id, right-clicking a
        // second step re-targets the popover and that same press then closes
        // it on release, so a third click would be needed.
        let target = (STEP_POPOVER_ID, popover.lane_id, popover.pattern, popover.step);
        let id = egui::Id::unique(target);
        Popup::new(id, ui.ctx().clone(), popover.at, ui.layer_id())
            .close_behavior(PopupCloseBehavior::CloseOnClickOutside)
            .open_bool(&mut open)
            .width(POPOVER_WIDTH)
            .gap(theme::ITEM_SPACING)
            .show(|ui| {
                // Which step is being edited, because the popover covers its
                // neighbours and the grid cannot say so itself. One-based, as
                // the length field and the pattern buttons count.
                let title = format!("{} · step {}", lane.name, popover.step + 1);
                let title = RichText::new(title).color(theme::TEXT_DIM);
                ui.add(Label::new(title).truncate().selectable(false));

                // The rails get what is left of the popover's width once the
                // labels beside them have had theirs, so they all line up.
                ui.spacing_mut().slider_width = POPOVER_WIDTH - POPOVER_LABEL_WIDTH;

                // Velocity: the same value a vertical drag on the cell sets,
                // here as a number for when it has to be exact.
                ui.add(
                    Slider::from_get_set(
                        grid_math::VELOCITY_WIDGET_MIN..=grid_math::VELOCITY_WIDGET_MAX,
                        |value| {
                            if let Some(value) = value {
                                let velocity = grid_math::widget_velocity(value);
                                write_field(model, pattern, &popover, |step| {
                                    step.with_velocity(velocity)
                                });
                            }
                            f64::from(lane_data.step(popover.step).velocity())
                        },
                    )
                    .integer()
                    .text("Velocity"),
                );

                // Pan. The rail is in packed units — one detent per value the
                // step can hold ([`grid_math::PAN_WIDGET_MIN`]) — and reads
                // out as the left/right percentage the host will be sent.
                //
                // Behind the `pan-expression` feature, which is in `default`
                // and exists so pan can be dropped if no host honours it: a
                // build that does not send the expression must not offer a
                // control for it, since nothing downstream would act on what it
                // set. The step's pan bits and everything in `grid_math` that
                // maps them stay either way, so turning the feature back on
                // brings the slider back to the values a project already holds.
                #[cfg(feature = "pan-expression")]
                ui.add(
                    Slider::from_get_set(
                        grid_math::PAN_WIDGET_MIN..=grid_math::PAN_WIDGET_MAX,
                        |value| {
                            if let Some(value) = value {
                                let pan = grid_math::widget_pan(value);
                                write_field(model, pattern, &popover, |step| step.with_pan(pan));
                            }
                            f64::from(lane_data.step(popover.step).pan())
                        },
                    )
                    .integer()
                    .text("Pan")
                    .custom_formatter(|value, _| {
                        grid_math::pan_label(grid_math::widget_pan(value))
                    })
                    .custom_parser(|text| grid_math::parse_pan_label(text).map(f64::from)),
                );

                // Pitch, in semitones: the same value pitch mode draws.
                ui.add(
                    Slider::from_get_set(
                        grid_math::PITCH_WIDGET_MIN..=grid_math::PITCH_WIDGET_MAX,
                        |value| {
                            if let Some(value) = value {
                                let pitch = grid_math::widget_pitch(value);
                                write_field(model, pattern, &popover, |step| {
                                    step.with_pitch(pitch)
                                });
                            }
                            f64::from(lane_data.step(popover.step).pitch())
                        },
                    )
                    .integer()
                    .text("Pitch")
                    .custom_formatter(|value, _| {
                        grid_math::pitch_label(grid_math::widget_pitch(value))
                    }),
                );

                // Ratchet: the effective count, which is what `Step` takes and
                // gives — the `n - 1` packing never leaves `model.rs`.
                ui.add(
                    Slider::from_get_set(
                        grid_math::RATCHET_WIDGET_MIN..=grid_math::RATCHET_WIDGET_MAX,
                        |value| {
                            if let Some(value) = value {
                                let ratchet = grid_math::widget_ratchet(value);
                                write_field(model, pattern, &popover, |step| {
                                    step.with_ratchet(ratchet)
                                });
                            }
                            f64::from(lane_data.step(popover.step).ratchet())
                        },
                    )
                    .integer()
                    .text("Ratchet"),
                );

                // Probability, in the percent the field itself stores.
                ui.add(
                    Slider::from_get_set(
                        grid_math::PROBABILITY_WIDGET_MIN..=grid_math::PROBABILITY_WIDGET_MAX,
                        |value| {
                            if let Some(value) = value {
                                let chance = grid_math::widget_probability(value);
                                write_field(model, pattern, &popover, |step| {
                                    step.with_probability(chance)
                                });
                            }
                            f64::from(lane_data.step(popover.step).probability())
                        },
                    )
                    .integer()
                    .suffix("%")
                    .text("Chance"),
                );
            });

        if !open {
            self.popover = None;
        }
    }

    /// The wheel over the grid, spent on the scroll offset (the strip scrolls
    /// horizontally, the lanes vertically).
    ///
    /// Whatever is *left* of the wheel. This runs after the headers and the
    /// top bar, so a notch over a lane's key field has already been banked
    /// by [`scroll_key`] and one over an open rate dropdown has already
    /// scrolled its list: egui's convention is that the widget under the
    /// pointer consumes the scroll it uses, and the grid is the backstop.
    /// Being last costs a frame — the delta is spent on the offset the
    /// *next* frame draws through — which at [`REPAINT_INTERVAL`] is
    /// invisible, and is what buys the widgets their first refusal.
    ///
    /// The offset runs the other way from the delta, which says how the
    /// *content* should move. Shift-wheel needs no handling here: egui's own
    /// wheel state applies `horizontal_scroll_modifier` before any of this,
    /// so a shifted notch arrives on the `x` axis already.
    fn scroll_grid(&mut self, ui: &egui::Ui, layout: &EditorLayout) {
        let Some(pos) = ui.input(|input| input.pointer.hover_pos()) else {
            return;
        };
        // The headers scroll with the strip, so a wheel over either moves
        // it; the top bar is not part of the grid, and neither is anything
        // outside the window.
        let zone = layout.zone(pos);
        if !matches!(zone, Zone::Steps | Zone::LaneHeader | Zone::Panel) {
            return;
        }

        let mut delta = ui.input_mut(|input| std::mem::take(&mut input.smooth_scroll_delta));
        // The panel has one row: only its sideways scroll moves the grid.
        if zone == Zone::Panel {
            delta.y = 0.0;
        }
        // A non-finite delta would poison the offset for every later frame;
        // `clamp_scroll` would pull it back to the origin, which reads as the
        // grid jumping home for no reason.
        if delta == Vec2::ZERO || !delta.is_finite() {
            return;
        }
        self.scroll -= delta;
    }

    /// Settles the step strip's scroll offset for this frame, and hands back
    /// the view everything else is drawn and hit-tested through.
    ///
    /// Two things can move the offset before a frame may use it:
    ///
    /// * follow mode, which scrolls the playhead's column into view;
    /// * the content having moved under it since the last frame — a lane
    ///   deleted, a loop shortened, the window resized — which
    ///   [`GridView::clamp_scroll`] pulls it back for.
    ///
    /// A viewport does not depend on the offset, so one provisional view
    /// answers both questions and the final one is built from the result.
    fn settle_scroll(&mut self, layout: &EditorLayout, data: &SeqData, pattern: usize) -> GridView {
        let metrics = CellMetrics::from_theme();
        let (rows, steps) = (data.lane_count(), strip_steps(data, pattern));
        let probe = layout.grid_view(metrics, self.scroll);

        if self.follow && let Some(step) = follow_step(data, pattern, &self.playhead) {
            self.scroll.x = probe.follow_scroll_x(step, steps);
        }
        self.scroll = probe.clamp_scroll(self.scroll, steps, rows);
        layout.grid_view(metrics, self.scroll)
    }

    /// The pinned lane headers: one row per visible lane, each carrying that
    /// lane's controls.
    ///
    /// Real egui widgets rather than hand-painted ones, unlike the step
    /// strip: there are at most a screenful of them, they are the stock
    /// controls (a drag value, a dropdown, two toggles), and they inherit
    /// [`theme`]'s styling for free. What is *not* left to egui is where they
    /// go — [`HeaderFields`] places them from absolute rects so that every
    /// lane's columns line up however long its name is, and so that each row
    /// sits exactly on its own row of cells.
    fn ui_lane_headers(
        &mut self,
        ui: &mut egui::Ui,
        layout: &EditorLayout,
        view: &GridView,
        data: &SeqData,
        pattern: usize,
    ) {
        // The backstop for a reorder whose row left the column: a lane
        // dragged past the last visible row stops being drawn, and with it
        // the one place [`reorder_lane`] could notice the button had come up.
        // No button down means no gesture, whoever it belonged to.
        if !ui.input(|input| input.pointer.any_down()) {
            self.lane_drag = None;
        }

        let headers = layout.headers();
        if !headers.is_positive() {
            return;
        }
        let any_solo = data.any_solo();
        let selected_row = self.selected_row(data);
        if let Some(edit) = self.name_edit.as_mut() {
            edit.shown = false;
        }

        ui.scope_builder(UiBuilder::new().max_rect(headers), |ui| {
            // A row the vertical scroll has taken out of the column must not
            // draw over the top bar or past the window.
            ui.shrink_clip_rect(headers);

            for row in view.visible_rows(data.lane_count()) {
                // Both are `Some` for every row below `lane_count`, as in
                // `paint_steps`; a row that somehow has no data is skipped
                // rather than unwrapped, because this runs inside the host.
                let (Some(lane), Some(lane_data)) = (data.lane(row), data.lane_data(pattern, row))
                else {
                    continue;
                };
                let place = HeaderPlace {
                    band: layout.header_row(view, row),
                    row,
                    pitch: view.metrics().row_pitch(),
                    content_top: view.origin().y,
                    selected: self.panel_open && selected_row == Some(row),
                };
                let audible = lane_is_audible(lane, any_solo);
                self.ui_lane_header(ui, place, lane, lane_data, pattern, audible);
            }
        });
        // A name field whose row was not drawn has lost the keyboard without
        // being told: that is leaving the field, so the name is saved.
        if let Some(edit) = self.name_edit.take_if(|edit| !edit.shown)
            && let Some(lane) = data.position_of(edit.lane_id).and_then(|pos| data.lane(pos))
        {
            save_name(&self.model, lane, edit);
        }
        self.continue_lane_drag(ui, layout, view, data);
    }

    /// The rest of a lane reorder once [`reorder_lane`] has picked the lane
    /// up: follow the pointer, scroll the list when it nears an edge, drop
    /// on release, put the lane back on Escape.
    ///
    /// Here, once a frame, rather than in the dragged lane's own row: the
    /// lane can be carried to a row that is not drawn (past the bottom of the
    /// window, or scrolled away), and a row that is not drawn runs no code.
    fn continue_lane_drag(
        &mut self,
        ui: &egui::Ui,
        layout: &EditorLayout,
        view: &GridView,
        data: &SeqData,
    ) {
        let Some(held) = self.lane_drag.as_mut() else {
            return;
        };
        // Escape first: egui ends the drag on Escape too, so by the time the
        // button is looked at the key is all that says the drag was
        // abandoned rather than finished.
        if ui.input(|input| input.key_pressed(egui::Key::Escape)) {
            if held.drag.target() != held.drag.from() {
                self.model.move_lane(held.lane_id, held.drag.from());
            }
            self.lane_drag = None;
            return;
        }
        if !ui.input(|input| input.pointer.primary_down()) {
            // Dropped: the lane is already where it was let go.
            self.lane_drag = None;
            return;
        }
        let Some(pos) = ui.input(|input| input.pointer.interact_pos()) else {
            return;
        };

        let headers = layout.headers();
        let pitch = view.metrics().row_pitch();
        let step = grid_math::edge_scroll(pos.y, headers.min.y, headers.max.y, pitch, pitch * 0.5);
        if step != 0.0 {
            // Clamped by the next frame's `settle_scroll`.
            self.scroll.y += step;
        }
        let content_y = pos.y - view.origin().y;
        if let Some(target) = held.drag.enter(content_y, data.lane_count()) {
            // A refusal means the lane has gone (a state load mid-drag); the
            // next frame has no row for it and the release ends the drag.
            self.model.move_lane(held.lane_id, target);
        }
    }

    /// One lane's header: drag grip, colour dot, name, key, length, rate,
    /// mute, solo — and the context menu behind the first three.
    ///
    /// Every control writes straight through [`SeqModel`] — a value edit for
    /// all of them except a length past the lane's capacity, which
    /// [`LengthEdit`] turns into a grow followed by a value edit. Nothing is
    /// cached between frames except the text in the rename field, so the row
    /// always shows what the audio thread will read next.
    fn ui_lane_header(
        &mut self,
        ui: &mut egui::Ui,
        place: HeaderPlace,
        lane: &Lane,
        lane_data: &LaneData,
        pattern: usize,
        audible: bool,
    ) {
        // Field borrows rather than `self.…` inside the closures below: the
        // key field writes through the model while banking its scroll in
        // `key_scroll`, and either a method call or a `self` capture would
        // borrow all of `self` at once.
        let model = &self.model;
        let key_scroll = &mut self.key_scroll;
        let lane_drag = &mut self.lane_drag;
        let rename = &mut self.rename;
        let name_edit = &mut self.name_edit;
        let confirm = &mut self.confirm;
        let rng = &mut self.rng;
        let selected_lane = &mut self.selected_lane;

        let band = place.band;
        let fields = HeaderFields::split(band.shrink2(egui::vec2(theme::PANEL_PADDING, 0.0)));
        let colour = theme::rgb(lane.colour);
        let text = if audible { theme::TEXT } else { theme::TEXT_DIM };

        // The row gets its own id scope, keyed by the lane — see
        // [`LANE_HEADER_ID`]. Everything below is positioned from `fields`
        // rather than laid out, so the scope is there for the ids alone.
        let row = UiBuilder::new().max_rect(band).id_salt((LANE_HEADER_ID, lane.id));
        ui.scope_builder(row, |ui| {
            // The lane handle: the grip, the dot and the name answer the
            // pointer as one region ([`HeaderFields::handle`]) — dragged to
            // reorder the lane, right-clicked for everything about it that is
            // not in this row.
            //
            // `click_and_drag`, unlike the step strip's `drag` alone: here the
            // click-or-drag decision is egui's two-outcome one, and the delay
            // is what a hand wants — a right-click that wobbled must open the
            // menu rather than reorder the lane list.
            let handle = ui.interact(
                fields.handle(),
                ui.scope_id().with(LANE_HANDLE_ID),
                Sense::click_and_drag(),
            );
            let dragging = reorder_lane(ui, &handle, lane_drag, lane, place);
            if handle.clicked() {
                // The lane the parameter panel edits.
                *selected_lane = Some(lane.id);
            }
            // A double-click on the name (not the grip or the dot) types a
            // new one in place ([`NameEdit`]).
            let pointer = handle.interact_pointer_pos();
            let on_name = pointer.is_some_and(|pos| fields.name.contains(pos));
            let editing = name_edit.as_ref().is_some_and(|edit| edit.lane_id == lane.id);
            if handle.double_clicked() && on_name && !editing {
                let text = lane.name.clone();
                *name_edit = Some(NameEdit { lane_id: lane.id, text, opening: true, shown: true });
            }
            if place.selected {
                ui.painter().rect_filled(band, CornerRadius::ZERO, theme::SELECTED_ROW);
                let mark = Rect::from_min_size(
                    band.min,
                    egui::vec2(theme::SELECTED_MARK_WIDTH, band.height()),
                );
                ui.painter().rect_filled(mark, CornerRadius::ZERO, theme::ACCENT);
            }
            if dragging {
                // The row being carried, washed so the hand can see what it
                // picked up. Under the controls, which are drawn after.
                ui.painter().rect_filled(band, CornerRadius::ZERO, theme::ROW_DRAG);
            }
            if handle.hovered() || dragging {
                let icon = if dragging { CursorIcon::Grabbing } else { CursorIcon::Grab };
                ui.ctx().set_cursor_icon(icon);
            }
            let target = MenuLane { lane, pattern, step_beats: lane_data.rate().rate_beats() };
            lane_menu(&handle, model, rename, confirm, rng, target);

            // The grip's dots, painted rather than a glyph — see
            // [`grid_math::grip_dots`]. Brightened under the pointer, which is
            // the only hint the row gives that it can be picked up.
            let grip = if handle.hovered() || dragging { theme::TEXT } else { theme::GRIP };
            for dot in grid_math::grip_dots(fields.grip) {
                ui.painter().circle_filled(dot, theme::GRIP_DOT_RADIUS, grip);
            }

            // The lane's colour, painted rather than a widget: the palette is
            // in the context menu, where the rest of the lane's settings are.
            // Dimmed with the lane, so a muted row reads as muted all the way
            // across.
            ui.painter().circle_filled(
                fields.dot.center(),
                theme::LANE_DOT_RADIUS,
                if audible { colour } else { theme::dim(colour, theme::MUTED_FACTOR) },
            );

            // The name: left-aligned and truncated, because it is what the eye
            // finds the row by and a long one may not push the controls out of
            // line. A double-click types a new one in place; renaming is also
            // in the context menu behind it.
            match name_edit.as_mut().filter(|edit| edit.lane_id == lane.id) {
                Some(edit) => match name_field(ui, fields.name, edit) {
                    Some(NameEditEnd::Save) => {
                        let edit = name_edit.take().expect("the edit just drawn");
                        save_name(model, lane, edit);
                    }
                    Some(NameEditEnd::Cancel) => *name_edit = None,
                    None => {}
                },
                None => {
                    let layout = Layout::left_to_right(Align::Center);
                    ui.scope_builder(UiBuilder::new().max_rect(fields.name).layout(layout), |ui| {
                        let name = RichText::new(&lane.name).color(text);
                        ui.add(Label::new(name).truncate().selectable(false));
                    });
                }
            }

            // The key, shown and typed as a note name. A drag value because
            // the key is changed by dragging or scrolling: egui gives the
            // drag, and `scroll_key` below adds the scroll.
            let (key, steps) = put_stepped(
                ui,
                fields.key,
                DragValue::from_get_set(|value| {
                    if let Some(value) = value {
                        model.set_key(lane.id, grid_math::widget_key(value));
                    }
                    f64::from(lane.key())
                })
                .speed(KEY_DRAG_SPEED)
                .range(0..=Lane::KEY_MAX)
                .custom_formatter(|value, _| grid_math::note_name(grid_math::widget_key(value)))
                .custom_parser(|text| grid_math::parse_note_name(text).map(f64::from)),
            );
            if steps != 0 {
                let wanted = f64::from(lane.key()) + f64::from(steps);
                model.set_key(lane.id, grid_math::widget_key(wanted));
            }
            scroll_key(ui, &key, model, lane, key_scroll);

            // The loop length. `LengthEdit` works out whether the lane has room
            // for what was asked; growing it is a shape edit, so it goes first
            // and the length lands in the republished data.
            let set_length = |value: f64| {
                let edit = LengthEdit::resolve(value, lane_data.capacity());
                // A failed grow means the lane is gone (a state load between
                // frames), and then the length has nowhere to go either —
                // `set_length` would answer `false` as well.
                let grown =
                    edit.grow().is_none_or(|steps| model.ensure_capacity(pattern, lane.id, steps));
                if grown {
                    model.set_length(pattern, lane.id, edit.length());
                }
            };
            let (length, steps) = put_stepped(
                ui,
                fields.length,
                DragValue::from_get_set(|value| {
                    if let Some(value) = value {
                        set_length(value);
                    }
                    // The lane data this frame is holding, so a grow shows one
                    // frame late. The drag itself does not care: egui keeps its
                    // own precise value for the length of the gesture.
                    f64::from(lane_data.length())
                })
                .speed(LENGTH_DRAG_SPEED)
                // Whole steps: egui picks decimals from the drag speed, which
                // would show "16.0".
                .fixed_decimals(0)
                .range(LengthEdit::MIN..=LengthEdit::MAX)
                .clip_text(true),
            );
            if steps != 0 {
                set_length(f64::from(lane_data.length()) + f64::from(steps));
            }
            length.on_hover_text(LENGTH_HOVER);

            // The rate: every `Rate`, labelled by its own `Display` (21 of them,
            // so a list rather than a cycle button).
            let rate = lane_data.rate();
            ui.scope_builder(
                UiBuilder::new().max_rect(fields.rate).layout(Layout::left_to_right(Align::Center)),
                |ui| {
                    ComboBox::from_id_salt(RATE_COMBO_ID)
                        .selected_text(rate.to_string())
                        .width(fields.rate.width())
                        .wrap_mode(TextWrapMode::Truncate)
                        .show_ui(ui, |ui| {
                            for option in Rate::ALL {
                                let item = ui.selectable_label(option == rate, option.to_string());
                                if item.clicked() {
                                    model.set_rate(pattern, lane.id, option);
                                }
                            }
                        });
                },
            );

            // The lane's volume, sent with every note as a per-note volume.
            // Drag, click to type, right-click for 0 dB.
            let (volume, steps) = put_stepped(
                ui,
                fields.volume,
                DragValue::from_get_set(|value| {
                    if let Some(value) = value {
                        model.set_volume(lane.id, grid_math::widget_volume(value));
                    }
                    f64::from(lane.volume_db())
                })
                .speed(VOLUME_DRAG_SPEED)
                .range(Lane::VOLUME_MIN..=Lane::VOLUME_MAX)
                .custom_formatter(|value, _| {
                    grid_math::volume_label(grid_math::widget_volume(value))
                })
                .custom_parser(|text| grid_math::parse_volume(text).map(f64::from)),
            );
            if steps != 0 {
                let wanted = f64::from(lane.volume_db()) + f64::from(steps);
                model.set_volume(lane.id, grid_math::widget_volume(wanted));
            }
            if volume.secondary_clicked() {
                model.set_volume(lane.id, 0);
            }
            volume.on_hover_text(
                "Lane volume. Drag up or down, or click to type. Right-click for 0 dB.",
            );

            // Mute and solo. Read back off the lane rather than toggled from a
            // copy, so a click lands on whatever the state is now.
            if ui.put(fields.mute, Button::new("M").selected(lane.is_muted())).clicked() {
                model.set_mute(lane.id, !lane.is_muted());
            }
            if ui.put(fields.solo, Button::new("S").selected(lane.is_soloed())).clicked() {
                model.set_solo(lane.id, !lane.is_soloed());
            }
        });
    }

    /// The top bar's `+ lane` button.
    ///
    /// A shape edit, so it goes through [`SeqModel::add_lane`] and the new
    /// lane appears in the sequence the *next* frame draws — the same one
    /// frame's delay a capacity grow has. The button is disabled rather than
    /// silently refused at [`MAX_LANES`]: the cap is the model's, and a
    /// control that does nothing has to say why.
    fn ui_add_lane(&mut self, ui: &mut egui::Ui, layout: &EditorLayout, data: &SeqData) {
        let slot = layout.add_lane_button();
        if !slot.is_positive() {
            return;
        }

        let model = &self.model;
        let full = data.lane_count() >= MAX_LANES;
        let mut builder = UiBuilder::new().max_rect(slot);
        if full {
            builder = builder.disabled();
        }
        ui.scope_builder(builder, |ui| {
            let button = ui.put(slot, Button::new(ADD_LANE_LABEL));
            if button.clicked() {
                let (name, colour, key, channel) = new_lane_fields(data);
                // The id is the model's answer for a GUI that wants to select
                // the lane it just made; nothing here does yet.
                let _ = model.add_lane(name, colour, key, channel);
            }
            let hint = if full {
                format!("This instance already holds its {MAX_LANES} lanes")
            } else {
                "Add a lane below the last one".to_owned()
            };
            button.on_hover_text(hint);
        });
    }

    /// The eight pattern buttons at the left end of the top bar.
    ///
    /// Two things are read, because the parameter and the sequence disagree for
    /// as long as a switch takes: the button drawn as selected is the pattern
    /// the engine is *playing* — [`Playhead::pattern`], published only once
    /// every lane has reached it — while the one `patsel` asks for is accented
    /// until the switch lands. With nothing playing the parameter is all there
    /// is, so its own button is the selected one and nothing is ever left
    /// unlit.
    fn ui_pattern_bar(&mut self, ui: &mut egui::Ui, layout: &EditorLayout, data: &SeqData) {
        let song = data.song.is_on();
        let playing = self.playhead.pattern().and_then(grid_math::pattern_index_button);
        let shown = self.shown_pattern();
        if self.paged_for != Some(shown) {
            self.paged_for = Some(shown);
            self.pattern_page = grid_math::pattern_page(shown);
        }

        let arrows = [(0, -1, "‹", "Previous 8 patterns"), (1, 1, "›", "Next 8 patterns")];
        for (side, direction, label, hover) in arrows {
            let slot = layout.page_button(side);
            if !slot.is_positive() {
                continue;
            }
            if ui.put(slot, Button::new(label)).on_hover_text(hover).clicked() {
                self.pattern_page = grid_math::step_page(self.pattern_page, direction);
            }
        }

        for button_index in 0..grid_math::PATTERN_BUTTONS {
            let slot = layout.pattern_button(button_index);
            let Some(index) = grid_math::page_pattern(self.pattern_page, button_index) else {
                continue;
            };
            if !slot.is_positive() {
                continue;
            }
            let number = index + 1;
            // In song mode the song picks what plays, so the lit button is
            // the pattern being edited and the playing one is accented. Out
            // of it, the lit button is the one playing and the accent marks
            // one asked for but not yet reached.
            let (lit, accent, hover) = if song {
                let playing_here = playing == Some(index) && shown != index;
                let hover = match playing_here {
                    true => format!("Pattern {number} is playing in the song. Click to edit it."),
                    false => format!("Edit pattern {number}. Right-click to copy it."),
                };
                (shown == index, playing_here, hover)
            } else {
                let active = playing.unwrap_or(shown) == index;
                let pending = shown == index && !active;
                let hover = match pending {
                    true => format!("Pattern {number} — lanes switch at their next step"),
                    false => format!("Play pattern {number}. Right-click to copy it."),
                };
                (active, pending, hover)
            };
            let mut label = RichText::new(number.to_string());
            if accent {
                label = label.color(theme::ACCENT);
            }
            let button = ui.put(slot, Button::new(label).selected(lit));
            if button.clicked() {
                self.set_pattern(index);
            }
            self.pattern_menu(&button, data, index);
            button.on_hover_text(hover);
        }
    }

    /// The song row, shown while song mode is on: the order as typed on the
    /// left, and one cell per entry over the step strip.
    ///
    /// The cells show each entry's pattern. The entry playing is filled with
    /// the accent (with a line under it filling up through an entry longer
    /// than a bar), and the entries that play the pattern on screen are
    /// outlined, so the grid's pattern can be found in the song. Clicking a
    /// cell shows its pattern in the grid.
    fn ui_song_bar(
        &mut self,
        ui: &mut egui::Ui,
        layout: &EditorLayout,
        data: &SeqData,
        shown: usize,
    ) {
        if layout.song_bar().height() <= 0.0 {
            // Song mode is off: forget the typing, so the field opens fresh.
            self.song_edit = None;
            return;
        }
        let song = &data.song;
        // The bar length the audio thread last saw: until the host has said,
        // 4/4.
        let lengths = PatternBars::new(data, self.playhead.bar_beats());

        let slot = layout.song_text();
        if slot.is_positive() {
            let model = &self.model;
            let held = self.song_edit.get_or_insert_with(|| song.text.clone());
            let field = ui.put(
                slot,
                TextEdit::singleline(held)
                    .id_salt(SONG_TEXT_ID)
                    .hint_text("Pattern order: 1-2-1-3x2")
                    .desired_width(slot.width()),
            );
            if field.changed() {
                // A half-typed song is left unwritten until it reads as one.
                let _ = model.set_song(held);
            } else if !field.has_focus() && *held != song.text {
                // A load moved the song under the buffer, or the field was
                // left holding text that never read as a song.
                *held = song.text.clone();
            }
            let hover = match parse_song(held) {
                Ok(_) => format!(
                    "The patterns to play from the start of the song, each to its end. \
                     \"1-2-1-3\" plays 1, 2, 1, 3; \"4x2\" plays 4 twice; 0 is a silent bar. \
                     {} bars.",
                    song.total_bars(&lengths)
                ),
                Err(error) => {
                    let stroke = egui::Stroke::new(theme::HAIRLINE, theme::WARN);
                    let corner = theme::CONTROL_CORNER;
                    ui.painter().rect_stroke(field.rect, corner, stroke, StrokeKind::Outside);
                    format!("{error}. The song keeps playing what it had.")
                }
            };
            field.on_hover_text(hover);
        }

        let strip = layout.song_strip();
        if !strip.is_positive() {
            return;
        }
        let entries = song.len();
        // One more cell than entries: the end marker.
        let cells = entries + 1;
        let response = ui.interact(strip, egui::Id::unique(SONG_STRIP_ID), Sense::click());
        if response.hovered() {
            let delta = ui.input_mut(|input| std::mem::take(&mut input.smooth_scroll_delta));
            if delta.is_finite() {
                self.song_scroll -= delta.x + delta.y;
            }
        }
        // A bar playing in no entry is past the end: the end marker lights.
        let bar = self.playhead.song_bar();
        let playing = match self.playhead.song_entry() {
            Some(entry) => Some((entry as usize).min(entries)),
            None => bar.map(|_| entries),
        };
        if self.follow && let Some(cell) = playing {
            let scroll = self.song_scroll;
            self.song_scroll = grid_math::song_follow(scroll, strip.width(), entries, cell);
        }
        let max = grid_math::song_max_scroll(strip.width(), entries);
        self.song_scroll = self.song_scroll.max(0.0).min(max);
        let scroll = self.song_scroll;

        let painter = ui.painter_at(strip);
        if entries == 0 {
            painter.text(
                strip.left_center(),
                Align2::LEFT_CENTER,
                "Type the pattern order on the left to start the song",
                FontId::proportional(theme::HINT_SIZE * 0.8),
                theme::TEXT_DIM,
            );
        }
        let font = FontId::proportional(theme::PITCH_LABEL_SIZE + 2.0);
        let looped = song.is_looped();
        for index in grid_math::song_visible(strip.width(), scroll, cells) {
            let cell = grid_math::song_cell(strip, scroll, index);
            let here = playing == Some(index);
            if index == entries {
                // The switch for what happens after the last entry.
                let (label, colour) = match (looped, here) {
                    (true, _) => ("loop", theme::ACCENT),
                    (false, true) => ("end", theme::ACCENT),
                    (false, false) => ("end", theme::TEXT_DIM),
                };
                let stroke = egui::Stroke::new(theme::HAIRLINE, colour);
                painter.rect_stroke(cell, theme::CELL_CORNER, stroke, StrokeKind::Inside);
                let small = FontId::proportional(theme::PITCH_LABEL_SIZE);
                painter.text(cell.center(), Align2::CENTER_CENTER, label, small, colour);
                continue;
            }
            let entry = song.entries[index];
            let fill = match (here, (index / theme::SONG_ENTRY_GROUP) % 2 == 1) {
                (true, _) => theme::ACCENT,
                (false, true) => theme::CELL_SHADED,
                (false, false) => theme::CELL,
            };
            painter.rect_filled(cell, theme::CELL_CORNER, fill);
            if usize::from(entry) == shown {
                let stroke = egui::Stroke::new(theme::HAIRLINE, theme::ACCENT);
                painter.rect_stroke(cell, theme::CELL_CORNER, stroke, StrokeKind::Inside);
            }
            let label = match entry {
                Song::REST => "·".to_owned(),
                pattern => (usize::from(pattern) + 1).to_string(),
            };
            let colour = if here { theme::WINDOW } else { theme::TEXT };
            painter.text(cell.center(), Align2::CENTER_CENTER, label, font.clone(), colour);
            // An entry longer than a bar shows how far through it the song is.
            if here
                && let Some(bar) = bar
                && let Some(pos) = song.positions(&lengths).nth(index)
                && pos.bars > 1
            {
                let done = (i64::from(bar) - pos.start_bar + 1) as f32 / pos.bars as f32;
                let width = cell.width() * done.clamp(0.0, 1.0);
                let mut line = cell;
                line.min.y = cell.max.y - theme::SONG_PROGRESS_HEIGHT;
                line.max.x = cell.min.x + width;
                painter.rect_filled(line, 0.0, theme::WINDOW);
            }
        }

        let hovered = response
            .hover_pos()
            .and_then(|pos| grid_math::song_cell_at(strip, scroll, pos))
            .filter(|&index| index <= entries);
        let clicked = response
            .clicked()
            .then(|| response.interact_pointer_pos())
            .flatten()
            .and_then(|pos| grid_math::song_cell_at(strip, scroll, pos));
        if clicked == Some(entries) {
            self.model.set_song_looped(!looped);
        } else if let Some(&entry) = clicked.and_then(|index| song.entries.get(index))
            && let Some(pattern) = Song::pattern_of(entry)
        {
            self.set_pattern(pattern);
        }
        if hovered == Some(entries) {
            let text = match looped {
                true => "After the last pattern the song starts again from the first. \
                         Click to stop at the end instead.",
                false => "After the last pattern the song goes silent. \
                          Click to loop back to the first pattern instead.",
            };
            response.on_hover_text(text);
        } else if let Some(pos) = hovered.and_then(|index| song.positions(&lengths).nth(index)) {
            let bars = match pos.bars {
                1 => format!("Bar {}", pos.start_bar + 1),
                _ => format!("Bars {}-{}", pos.start_bar + 1, pos.end_bar()),
            };
            let text = match pos.pattern {
                Some(pattern) => format!("{bars}: pattern {}. Click to edit it.", pattern + 1),
                None => format!("{bars}: silent"),
            };
            response.on_hover_text(text);
        }
    }

    /// A pattern button's context menu: copy the pattern into another slot.
    ///
    /// A copy replaces everything in the target, and nothing can undo it, so
    /// a target that has notes takes two clicks, as the lane menu's delete
    /// and clear do. An empty target is copied into on the first click.
    fn pattern_menu(&mut self, button: &egui::Response, data: &SeqData, from: usize) {
        let model = &self.model;
        let armed = &mut self.pattern_copy;
        let shown = Popup::context_menu(button)
            .close_behavior(PopupCloseBehavior::CloseOnClickOutside)
            .show(|ui| {
                ui.label(format!("Copy pattern {} to", from + 1));
                let spacing = Vec2::splat(theme::ITEM_SPACING);
                egui::Grid::new(("bitstep:copy-targets", from)).spacing(spacing).show(ui, |ui| {
                    for to in 0..NUM_PATTERNS {
                        if to > 0 && to % grid_math::PATTERN_BUTTONS == 0 {
                            ui.end_row();
                        }
                        if to == from {
                            ui.add_enabled(false, Button::new((to + 1).to_string()));
                            continue;
                        }
                        let empty = pattern_is_empty(data, to);
                        let waiting = *armed == Some(PatternCopy { from, to });
                        let (label, hover) = match (waiting, empty) {
                            (true, _) => (
                                RichText::new(format!("{}?", to + 1)).color(theme::WARN),
                                format!(
                                    "Click again to replace pattern {} with pattern {}. \
                                     Ctrl+Z undoes it.",
                                    to + 1,
                                    from + 1
                                ),
                            ),
                            (false, true) => (
                                RichText::new((to + 1).to_string()),
                                format!("Copy into pattern {} (empty)", to + 1),
                            ),
                            (false, false) => (
                                RichText::new((to + 1).to_string()),
                                format!("Pattern {} has notes: click twice to replace it", to + 1),
                            ),
                        };
                        let item = ui.button(label).on_hover_text(hover);
                        if item.clicked() && pattern_copy_click(armed, from, to, empty) {
                            model.copy_pattern(from, to);
                            ui.close();
                        }
                    }
                });
            });
        // As with the lane menu, an arm does not outlive the menu it was made in.
        if shown.is_none() && armed.is_some_and(|copy| copy.from == from) {
            *armed = None;
        }
    }

    /// Writes `patsel` through the host: begin, set, end, inside the frame
    /// the click landed in.
    ///
    /// The whole gesture at once because a pattern button is a discrete
    /// choice rather than a drag — but a gesture all the same, since a bare
    /// `set` leaves a host recording automation with no idea the parameter
    /// has stopped moving.
    ///
    /// The parameter is not written here, only asked for: the wrapper queues
    /// the change and the value lands when the host plays the event back, so
    /// [`Self::shown_pattern`] — and with it the grid — follows a frame or a
    /// block later rather than instantly. That is the host's round trip, and
    /// the engine's own switch waits for a step boundary anyway.
    ///
    /// Nothing to write to while the window is shut ([`Self::editor_closed`]
    /// drops the context), and no click to serve then either.
    fn set_pattern(&self, button: usize) {
        let Some(context) = &self.gui_context else {
            return;
        };
        let setter = context.param_setter();
        setter.begin_set_parameter(&self.params.pattern_select);
        setter.set_parameter(&self.params.pattern_select, grid_math::pattern_button_value(button));
        setter.end_set_parameter(&self.params.pattern_select);
    }

    /// The row of the lane the parameter panel edits: the selected lane, or
    /// the first one when none is selected or the selected one has gone.
    fn selected_row(&self, data: &SeqData) -> Option<usize> {
        self.selected_lane
            .and_then(|id| data.position_of(id))
            .or_else(|| (data.lane_count() > 0).then_some(0))
    }

    /// The parameter the panel shows. Pan only in a build that sends it
    /// (the `pan-expression` feature, as the step popover's slider).
    fn shown_param(&self) -> ParamKind {
        if self.param == ParamKind::Pan && !cfg!(feature = "pan-expression") {
            ParamKind::Velocity
        } else {
            self.param
        }
    }

    /// The parameter panel under the grid: the selected lane's name and a
    /// button per parameter on the left, and one bar per step on the right that the
    /// pointer draws.
    ///
    /// Drawing works like pitch mode's but with absolute heights — the
    /// pointer's height is the value: press to set a step, drag sideways to
    /// draw across steps, hold Shift for a straight line from the pressed
    /// step. A right-click resets a step to its default.
    fn ui_param_panel(
        &mut self,
        ui: &mut egui::Ui,
        layout: &EditorLayout,
        data: &SeqData,
        pattern: usize,
    ) {
        let strip = layout.panel_strip();
        if !layout.panel().is_positive() {
            self.param_draw = None;
            return;
        }

        let painter = ui.painter();
        painter.rect_filled(layout.panel_header(), CornerRadius::ZERO, theme::PANEL);
        painter.rect_filled(strip, CornerRadius::ZERO, theme::WINDOW);
        let line = egui::Stroke::new(theme::HAIRLINE, theme::GRID_LINE);
        painter.hline(layout.panel().x_range(), layout.panel().min.y, line);
        painter.vline(layout.panel_header().max.x, layout.panel().y_range(), line);

        let kind = self.shown_param();
        let row = self.selected_row(data);
        let found = row.and_then(|row| data.lane(row).zip(data.lane_data(pattern, row)));
        let view = layout.panel_view(CellMetrics::from_theme(), self.scroll.x);
        let plot = strip.shrink2(egui::vec2(0.0, theme::PARAM_PLOT_INSET));
        let length = found
            .map_or(0, |(_, lane_data)| (lane_data.length() as usize).min(lane_data.capacity()));

        // The column under the pointer, clamped into the lane like a pitch
        // stroke, so a stroke that overshoots either end still reaches it.
        let step_under = |pos: Pos2| -> Option<usize> {
            let last = length.checked_sub(1)?;
            Some(match view.step_at(pos) {
                Some(step) => step.min(last),
                None => 0,
            })
        };

        // Input first, so this frame draws what the press wrote.
        let id = egui::Id::unique(PARAM_STRIP_ID);
        let response = ui.interact(strip, id, Sense::drag());
        if let Some((lane, lane_data)) = found {
            if response.hovered()
                && let Some((pos, button, _)) = ui.input(step_press)
                && let Some(step) = step_under(pos)
            {
                if button == PointerButton::Secondary {
                    let value = kind.default_value();
                    self.write_params(pattern, lane.id, lane_data, kind, &[(step, value)]);
                } else if button == PointerButton::Primary {
                    let draw = LevelDraw::begin(step, kind.value_at(plot, pos.y));
                    self.param_draw = Some(ParamStroke { lane_id: lane.id, kind, pattern, draw });
                }
            }
            if response.dragged_by(PointerButton::Primary) || response.drag_started() {
                let shift = ui.input(|input| input.modifiers.shift);
                if let Some(pos) = response.interact_pointer_pos()
                    && let Some(step) = step_under(pos)
                    && let Some(stroke) = self.param_draw.as_mut()
                    && stroke.lane_id == lane.id
                    && stroke.pattern == pattern
                {
                    let kind = stroke.kind;
                    let value = kind.value_at(plot, pos.y);
                    let read = |s: usize| kind.read(lane_data.step(s));
                    let writes = stroke.draw.draw_to(step, value, shift, read);
                    let lane_id = stroke.lane_id;
                    self.write_params(pattern, lane_id, lane_data, kind, &writes);
                }
            } else if !ui.input(|input| input.pointer.primary_down()) {
                self.param_draw = None;
            }
        } else {
            self.param_draw = None;
        }

        // The bars.
        let painter = ui.painter_at(strip);
        if let Some(centre) = kind.centre() {
            painter.hline(strip.x_range(), kind.y_of(plot, centre), line);
        }
        let mut readout = None;
        if let (Some((lane, lane_data)), Some(row)) = (found, row) {
            let colour = theme::rgb(lane.colour);
            let audible = lane_is_audible(lane, data.any_solo());
            let playing = grid_math::playhead_cell(
                pattern,
                self.playhead.pattern(),
                self.playhead.step(row),
                lane_data.length(),
            );
            let visible = view.visible_steps(length);
            for index in visible.clone() {
                let x = view.cell_rect(0, index).x_range();
                let slot = Rect::from_x_y_ranges(x, plot.y_range());
                painter.rect_filled(slot, theme::CELL_CORNER, theme::cell_background(index));
                let step = lane_data.step(index);
                let fill = match (step.is_on(), playing == Some(index)) {
                    (true, true) => theme::playhead_step_fill(colour, audible),
                    (true, false) => theme::on_step_fill(colour, audible),
                    (false, _) => theme::dim(colour, theme::MUTED_FACTOR),
                };
                let bar = kind.bar(plot, x, kind.read(step));
                painter.rect_filled(bar, CornerRadius::ZERO, fill);
            }
            // The grid's bar lines, carried down into the panel.
            let bar_line = egui::Stroke::new(theme::HAIRLINE, theme::BAR_LINE);
            for index in visible.clone().filter(|&index| theme::is_bar_start(index)) {
                painter.vline(view.column_boundary_x(index), plot.y_range(), bar_line);
            }
            if let Some(index) = playing.filter(|index| visible.contains(index)) {
                let x = view.cell_rect(0, index).x_range();
                let column = Rect::from_x_y_ranges(x, plot.y_range());
                painter.rect_filled(column, CornerRadius::ZERO, theme::PLAYHEAD);
            }

            // What the pointer is over (or drawing), for exact values.
            let pointer = response.interact_pointer_pos().or_else(|| response.hover_pos());
            if let Some(step) = pointer.and_then(step_under) {
                let value = kind.value_label(kind.read(lane_data.step(step)));
                let off = if lane_data.step(step).is_on() { "" } else { " (off)" };
                readout = Some(format!("Step {}: {value}{off}", step + 1));
            }
        }
        response.on_hover_text(
            "Draw with the mouse to set each step. Hold Shift for a straight line. \
             Right-click a step to reset it.",
        );

        // The left end: which lane, which parameter, and the readout.
        let inner = layout.panel_header().shrink(theme::PANEL_PADDING);
        let param = &mut self.param;
        ui.scope_builder(
            UiBuilder::new().max_rect(inner).layout(Layout::top_down(Align::Min)),
            |ui| {
                let Some((lane, _)) = found else {
                    let text = RichText::new("No lanes").color(theme::TEXT_DIM);
                    ui.add(Label::new(text).selectable(false));
                    return;
                };
                let name = RichText::new(&lane.name).color(theme::rgb(lane.colour));
                ui.add(Label::new(name).truncate().selectable(false));
                // One button per parameter, wrapping onto a second row only
                // if the column is too narrow for all of them.
                ui.horizontal_wrapped(|ui| {
                    ui.spacing_mut().item_spacing = Vec2::splat(theme::ITEM_SPACING);
                    for option in ParamKind::ALL {
                        if option == ParamKind::Pan && !cfg!(feature = "pan-expression") {
                            continue;
                        }
                        let button = Button::new(option.label()).selected(option == kind);
                        if ui.add(button).clicked() {
                            *param = option;
                        }
                    }
                });
                let hint = "Draw on any step";
                let text = readout.unwrap_or_else(|| hint.to_owned());
                let text = RichText::new(text).color(theme::TEXT_DIM);
                ui.add(Label::new(text).truncate().selectable(false));
            },
        );
    }

    /// Writes parameter values from the panel, on or off steps alike,
    /// skipping steps past the lane's length and values that would not
    /// change.
    fn write_params(
        &self,
        pattern: usize,
        lane_id: u32,
        lane_data: &LaneData,
        kind: ParamKind,
        writes: &[(usize, i32)],
    ) {
        let length = (lane_data.length() as usize).min(lane_data.capacity());
        for &(index, value) in writes {
            if index >= length {
                continue;
            }
            let step = lane_data.step(index);
            if kind.read(step) == value {
                continue;
            }
            self.model.update_step(pattern, lane_id, index, |step| kind.write(step, value));
        }
    }

    /// Undo and redo from the keyboard, and the commit that makes everything
    /// edited since the last quiet frame one undo step
    /// ([`SeqModel::commit_edits`]).
    ///
    /// A frame is quiet when no button is down and no gesture or text field
    /// is open: a paint drag, a length drag or a typed name is one step
    /// however many writes it made. While a text field has the keyboard,
    /// Ctrl+Z is left to it — egui's text fields have an undo of their own.
    fn handle_history(&mut self, ui: &egui::Ui) {
        if ui.ctx().text_edit_focused() {
            return;
        }
        let (mut undo, mut redo) = (0, 0);
        ui.input_mut(|input| {
            input.events.retain(|event| {
                let egui::Event::Key { key, pressed, modifiers, .. } = event else {
                    return true;
                };
                let Some(action) = keys::history_key(*key, *modifiers) else {
                    return true;
                };
                // Repeats count, so a held Ctrl+Z walks back; the release is
                // swallowed with the press so the host never sees half a key.
                match (action, *pressed) {
                    (keys::HistoryKey::Undo, true) => undo += 1,
                    (keys::HistoryKey::Redo, true) => redo += 1,
                    (_, false) => {}
                }
                false
            });
        });

        let busy = ui.input(|input| input.pointer.any_down())
            || self.gesture.is_some()
            || self.lane_drag.is_some()
            || self.param_draw.is_some();
        if busy {
            // Mid-gesture the shortcut is dropped: undoing under a drag would
            // have the drag's next write land on the restored sequence.
            return;
        }
        self.model.commit_edits();
        for _ in 0..undo {
            self.model.undo();
        }
        for _ in 0..redo {
            self.model.redo();
        }
    }

    /// Passes Space and shortcut keys on to the host's window ([`keys`]),
    /// and takes them out of this frame's input so no widget acts on them
    /// too. Not while a text field is being typed in.
    fn forward_host_keys(&mut self, ui: &egui::Ui, frame: &Frame) {
        if !self.key_forwarder_tried {
            self.key_forwarder_tried = true;
            self.key_forwarder = KeyForwarder::connect(frame);
        }
        let Some(forwarder) = &self.key_forwarder else {
            return;
        };
        if ui.ctx().text_edit_focused() {
            return;
        }
        ui.input_mut(|input| {
            input.events.retain(|event| {
                let egui::Event::Key { key, pressed, repeat, modifiers, .. } = event else {
                    return true;
                };
                let Some(keysym) = keys::forwarded_keysym(*key, *modifiers) else {
                    return true;
                };
                // A held key's repeats would start and stop the transport
                // over and over; the host gets the first press only.
                if !*repeat {
                    forwarder.send(keysym, *pressed, *modifiers);
                }
                false
            });
        });
    }

    /// The top bar: the eight pattern buttons on the left, `+ lane` and the
    /// follow toggle on the right, and the instance's vital signs in between.
    ///
    /// Real [`egui::Ui`] widgets rather than painted text, so the bar
    /// inherits the theme's styling; placed from [`EditorLayout`]'s rects
    /// rather than laid out, so the two controls stay at the right edge
    /// whatever the pattern bar does to the left of them.
    fn ui_top_bar(&mut self, ui: &mut egui::Ui, layout: &EditorLayout, data: &SeqData) {
        self.ui_add_lane(ui, layout, data);
        self.ui_pattern_bar(ui, layout, data);

        let slot = layout.panel_button();
        if slot.is_positive() {
            let toggle = ui.put(slot, Button::new(PANEL_LABEL).selected(self.panel_open));
            if toggle.clicked() {
                self.panel_open = !self.panel_open;
            }
            toggle.on_hover_text(
                "Show the parameter panel: draw velocity, pan, pitch, chance or ratchet \
                 for the selected lane",
            );
        }

        let slot = layout.follow_button();
        if slot.is_positive() {
            // A field borrow rather than `self.…` inside the branch, as in
            // `ui_lane_header`: a `self` capture would borrow all of it, and
            // the label below reads three other fields.
            let follow = &mut self.follow;
            let toggle = ui.put(slot, Button::new(FOLLOW_LABEL).selected(*follow));
            if toggle.clicked() {
                *follow = !*follow;
            }
            toggle.on_hover_text("Scroll the grid to keep the playhead in view");
        }

        let slot = layout.song_button();
        if slot.is_positive() {
            let on = data.song.is_on();
            let toggle = ui.put(slot, Button::new(SONG_LABEL).selected(on));
            if toggle.clicked() {
                self.model.set_song_on(!on);
            }
            toggle.on_hover_text(
                "Song mode: play patterns in the order you type, one per bar, \
                 following Bitwig's timeline",
            );
        }

        let history = [
            ("Undo", "Undo the last edit (Ctrl+Z)", self.model.can_undo()),
            ("Redo", "Redo the edit just undone (Ctrl+Shift+Z)", self.model.can_redo()),
        ];
        for (index, (label, hover, enabled)) in history.into_iter().enumerate() {
            let slot = layout.history_button(index);
            if !slot.is_positive() {
                continue;
            }
            // `ui.put`'s own scope, so the button can be greyed out when
            // there is nothing to step to.
            let scope = UiBuilder::new()
                .max_rect(slot)
                .layout(Layout::centered_and_justified(egui::Direction::TopDown));
            let button = ui.scope_builder(scope, |ui| ui.add_enabled(enabled, Button::new(label)));
            let button = button.inner.on_hover_text(hover);
            if button.clicked() {
                match index {
                    0 => self.model.undo(),
                    _ => self.model.redo(),
                };
            }
        }

        for (index, mode) in EditMode::ALL.into_iter().enumerate() {
            let slot = layout.mode_button(index);
            if !slot.is_positive() {
                continue;
            }
            let button = ui.put(slot, Button::new(mode.label()).selected(self.mode == mode));
            if button.clicked() {
                self.mode = mode;
            }
            button.on_hover_text(mode.hover());
        }

        let rest = layout.status_line();
        if !rest.is_positive() {
            return;
        }
        let line = format!(
            "bitstep {} ({}) — {} lane(s), pattern {}, playing {}",
            crate::Bitstep::VERSION,
            // Always `Some` here in practice — `build()` runs before the
            // window's first frame — but the field has to hold `None` while
            // the editor is closed, so there is a branch either way.
            match &self.gui_context {
                Some(ctx) => ctx.plugin_api().to_string(),
                None => "?".to_owned(),
            },
            data.lane_count(),
            self.params.pattern_select(),
            match self.playhead.pattern() {
                Some(index) => (index + 1).to_string(),
                None => "—".to_owned(),
            },
        );
        let line = match (data.song.is_on(), self.playhead.song_bar()) {
            (true, Some(bar)) => {
                let lengths = PatternBars::new(data, self.playhead.bar_beats());
                let total = data.song.total_bars(&lengths);
                format!("{line}, song bar {} of {total}", bar + 1)
            }
            _ => line,
        };
        // Truncated rather than allowed to grow into the toggle's slot.
        ui.scope_builder(
            UiBuilder::new().max_rect(rest).layout(Layout::left_to_right(Align::Center)),
            |ui| {
                ui.add(Label::new(line).truncate().selectable(false));
            },
        );
    }
}

/// The width of the strip in steps: the longest loop in the pattern on
/// screen, which is where its content ends.
///
/// The scroll bounds come from this rather than from
/// [`crate::model::MAX_STEPS`], so a project of 16-step lanes cannot be
/// scrolled into four thousand steps of nothing. The end handle of the
/// longest lane is still reachable — [`CellMetrics::content_size`] leaves
/// room for it past the last column.
fn strip_steps(data: &SeqData, pattern: usize) -> usize {
    (0..data.lane_count()).map(|row| row_length(data, pattern, row) as usize).max().unwrap_or(0)
}

/// The step column follow mode keeps in view: the rightmost one lit anywhere
/// in the grid, or `None` when nothing is playing the pattern on screen.
///
/// The rightmost rather than any particular lane's, because lanes run at
/// their own rates and lengths: there is no single
/// playhead column, and the one that leaves the viewport first is the
/// furthest right. [`grid_math::playhead_cell`] is what decides a row has a
/// cell lit at all, so follow mode and the paint agree about where playback
/// is down to the pattern and the lane's length.
fn follow_step(data: &SeqData, pattern: usize, playhead: &Playhead) -> Option<usize> {
    let playing = playhead.pattern();
    (0..data.lane_count())
        .filter_map(|row| {
            let length = row_length(data, pattern, row);
            grid_math::playhead_cell(pattern, playing, playhead.step(row), length)
        })
        .max()
}

/// The press the step strip acts on this frame, if there was one: where it
/// landed, which button it was, and what was held down with it.
///
/// Read from the raw events rather than from `pointer.press_origin()`,
/// which egui clears again on the release: for a tap that begins and ends
/// inside one frame — the case this exists for — the origin is already gone
/// by the time [`BitstepEditor::interact_steps`] looks, while the event still
/// carries the exact position the button went down at. The modifiers come
/// from the event for the same reason: by the release, `Alt` may have been
/// let go of.
///
/// Only the two buttons the grid answers to, so a middle-click or a
/// back-button press is not mistaken for one of them. The last press wins, so
/// a double-click fast enough to land both presses in one frame toggles once
/// rather than reading the first press's cell.
fn step_press(input: &egui::InputState) -> Option<(Pos2, PointerButton, Modifiers)> {
    input.events.iter().rev().find_map(|event| match event {
        egui::Event::PointerButton {
            pos,
            button: button @ (PointerButton::Primary | PointerButton::Secondary),
            pressed: true,
            modifiers,
        } => Some((*pos, *button, *modifiers)),
        _ => None,
    })
}

/// Wheel scroll over a lane's key field, banked until it is worth a semitone
/// (the key field is changed by dragging or scrolling).
///
/// The delta is *taken* out of the input state rather than read: otherwise
/// the same notch would move the key and scroll the lane list at once
/// ([`scroll_grid`] spends whatever is left), and egui's convention is that
/// the widget under the pointer consumes the scroll it uses.
fn scroll_key(
    ui: &egui::Ui,
    response: &egui::Response,
    model: &SeqModel,
    lane: &Lane,
    bank: &mut Option<KeyScroll>,
) {
    if !response.hovered() {
        return;
    }

    let delta = ui.input_mut(|input| std::mem::take(&mut input.smooth_scroll_delta.y));
    // Only one widget is hovered at a time, so a bank belonging to another
    // lane is simply stale: the pointer has moved on and its points go with
    // it rather than being spent on this lane's key.
    let banked = match bank {
        Some(banked) if banked.lane_id == lane.id => banked,
        _ => bank.insert(KeyScroll { lane_id: lane.id, points: 0.0 }),
    };

    banked.points += delta;
    let steps = grid_math::take_scroll_steps(&mut banked.points, grid_math::KEY_SCROLL_PITCH);
    if steps != 0 {
        model.set_key(lane.id, grid_math::nudge_key(lane.key(), steps));
    }
}

/// One of the popover's sliders, written through to the step it was opened on
/// (a value edit, straight to the model).
///
/// A free function rather than a method so that the slider closures can take
/// it while [`BitstepEditor::ui_step_popover`] holds a borrow of the model.
/// The `bool` is dropped for [`BitstepEditor::write_steps`]'s reason: a
/// refusal means the lane or the step has gone, which the next frame's lookup
/// closes the popover for.
fn write_field(
    model: &SeqModel,
    pattern: usize,
    popover: &StepPopover,
    f: impl FnOnce(Step) -> Step,
) {
    model.update_step(pattern, popover.lane_id, popover.step, f);
}

/// A seed for the editor's own [`Prng`], read from the clock once per
/// instance.
///
/// Randomise is a creative tool, so the dice have to differ between runs: a
/// fixed seed would hand every fresh instance the same first pattern, and
/// two instances in one project the same as each other. Nothing on the audio
/// thread reads this generator, and nothing in the test suite reads the
/// clock — the suite's determinism is about the sequencer's own [`Prng`],
/// which the engine seeds itself.
///
/// A clock that refuses to answer (a system time before the epoch) falls back
/// to [`Prng::DEFAULT_SEED`] rather than panicking inside the host.
/// Draws an in-place name edit ([`NameEdit`]) over the name's slot, and
/// says whether it ended this frame.
///
/// The first frame takes the keyboard and selects the whole name, so the
/// first key typed replaces it. After that the field is done as soon as it
/// no longer has the keyboard: egui gives it up on Enter, on Escape and on a
/// click elsewhere, and Escape is the one that leaves the name as it was.
fn name_field(ui: &mut egui::Ui, rect: Rect, edit: &mut NameEdit) -> Option<NameEditEnd> {
    edit.shown = true;
    let id = ui.make_persistent_id(NAME_EDIT_ID);
    let field = TextEdit::singleline(&mut edit.text).id(id).char_limit(LANE_NAME_LIMIT);
    let response = ui.put(rect, field);
    if std::mem::take(&mut edit.opening) {
        response.request_focus();
        let mut state = egui::text_edit::TextEditState::load(ui.ctx(), id).unwrap_or_default();
        let all = egui::text_selection::CCursorRange::select_all_str(&edit.text);
        state.cursor.set_char_range(Some(all));
        state.store(ui.ctx(), id);
        return None;
    }
    if response.has_focus() {
        return None;
    }
    let escaped = ui.input(|input| input.key_pressed(egui::Key::Escape));
    Some(if escaped { NameEditEnd::Cancel } else { NameEditEnd::Save })
}

/// Saves what an in-place name edit typed as `lane`'s name. A blank name
/// keeps the old one, and an unchanged one writes nothing: a rename is a
/// shape edit, which republishes the whole sequence.
fn save_name(model: &SeqModel, lane: &Lane, edit: NameEdit) {
    if !edit.text.trim().is_empty() && edit.text != lane.name {
        model.rename_lane(lane.id, edit.text);
    }
}

fn clock_seed() -> u64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map_or(Prng::DEFAULT_SEED, |since| since.as_nanos() as u64)
}

/// The lane `+ lane` adds: a name saying where it is in the list, the next
/// colour of the palette, and the key and channel of the lane it goes below.
///
/// Carrying the key on from the last lane rather than starting every new lane
/// at one fixed note: a kit is built upwards, so the next lane is usually the
/// next pad, and one semitone is both the likeliest guess and the shortest
/// correction. An instance with no lanes left starts at the first of
/// [`state::DEFAULT_LANES`]' keys, which is where its own first lane sat.
///
/// The colour comes from the *position*, so the list reads as a palette in
/// order however many lanes it holds ([`theme::lane_swatch_rgb`] cycles).
fn new_lane_fields(data: &SeqData) -> (String, u32, u8, u8) {
    let count = data.lane_count();
    let last = count.checked_sub(1).and_then(|row| data.lane(row));
    let (key, channel) = match last {
        Some(lane) => (grid_math::nudge_key(lane.key(), 1), lane.channel()),
        None => (state::DEFAULT_LANES[0].1, state::DEFAULT_CHANNEL),
    };
    (format!("Lane {}", count + 1), theme::lane_swatch_rgb(count), key, channel)
}

/// The reorder half of a lane header's handle (a lane is reordered by
/// dragging its handle). Answers whether this lane is the one being
/// dragged, which is what the row is washed and the cursor is set from.
///
/// Only the primary button reorders, named rather than left to `dragged()`:
/// the secondary button on this same handle opens the lane's menu
/// ([`lane_menu`]), and a right-press that wobbled must not also carry the
/// lane off down the list.
///
/// The lane is moved *as* the drag goes rather than on the release, so the
/// list under the hand is the answer — the state is the feedback, and that is
/// the reason there is no drop marker to draw. Each row it crosses is one
/// `move_lane`, which [`LaneReorder::enter`] is what keeps down to one per row
/// rather than one per frame.
///
/// Moving as it goes is what makes a cancel worth having: `Escape` puts the
/// lane back where the press found it, without leaving the gesture.
fn reorder_lane(
    ui: &egui::Ui,
    handle: &egui::Response,
    held: &mut Option<LaneDrag>,
    lane: &Lane,
    place: HeaderPlace,
) -> bool {
    if handle.drag_started_by(PointerButton::Primary) {
        // The *press's* position, not the pointer's now: egui does not call a
        // press a drag until the hand has moved past its click threshold, so
        // by this frame the pointer is already some way down the list, and
        // measuring from there would swallow the rows it has crossed.
        //
        // Where the press landed rather than where the row is, in turn, so
        // that a lane picked up near its bottom edge does not jump a row
        // before the hand has moved at all. The band's middle is the fallback
        // for a pointer egui has already forgotten the origin of, which reads
        // as a press in the middle of the row.
        let origin_y = ui
            .input(|input| input.pointer.press_origin())
            .or_else(|| handle.interact_pointer_pos())
            .map_or(place.band.center().y, |pos| pos.y);
        let drag = LaneReorder::begin(place.row, origin_y - place.content_top, place.pitch);
        *held = Some(LaneDrag { lane_id: lane.id, drag });
    }
    // The rest of the gesture — following the pointer, the drop, Escape — is
    // [`BitstepEditor::continue_lane_drag`]'s, once a frame.
    held.as_ref().is_some_and(|held| held.lane_id == lane.id)
}

/// Puts a whole-number drag value in `rect`, as `ui.put` would, and hands
/// back with its response how many steps the arrow keys asked for this
/// frame ([`arrow_steps`]).
fn put_stepped(ui: &mut egui::Ui, rect: Rect, drag: DragValue<'_>) -> (egui::Response, i32) {
    let scope = UiBuilder::new()
        .max_rect(rect)
        .layout(Layout::centered_and_justified(egui::Direction::TopDown));
    ui.scope_builder(scope, |ui| {
        // The id the drag value is about to take: it asks for the next auto
        // id before anything else.
        let steps = arrow_steps(ui, ui.next_auto_id());
        (ui.add(drag), steps)
    })
    .inner
}

/// Up and Down while the drag value with `id` is being typed in: +1 per Up,
/// −1 per Down, taken out of the input so the field does not see them.
///
/// egui's own handling adds the drag `speed` per press — a fraction of a
/// step for every field here — and the whole-number setters round that
/// straight back, so the keys did nothing at all.
fn arrow_steps(ui: &egui::Ui, id: egui::Id) -> i32 {
    if !ui.memory(|memory| memory.has_focus(id)) {
        return 0;
    }
    ui.input_mut(|input| {
        let up = input.count_and_consume_key(Modifiers::NONE, egui::Key::ArrowUp);
        let down = input.count_and_consume_key(Modifiers::NONE, egui::Key::ArrowDown);
        up as i32 - down as i32
    })
}

/// The lane a context menu is for, and what it needs to know about it.
#[derive(Clone, Copy)]
struct MenuLane<'a> {
    lane: &'a Lane,
    /// The pattern on screen, which the bulk edits and fills apply to.
    pattern: usize,
    /// The lane's step length in beats in that pattern, for the fills.
    step_beats: f64,
}

/// One lane's context menu: rename, colour, channel, duplicate, delete, the
/// four bulk edits and the fills.
///
/// Everything here is a `SeqModel` call and nothing is buffered but the text
/// being typed, so the grid behind the menu shows each item's effect as it is
/// chosen. The menu closes on the one-shot items (there is nothing more to
/// say to a lane that was just deleted or rotated) and stays open on the three
/// that are settings — a colour is chosen by trying colours, and a channel by
/// dragging one.
///
/// `delete` and `clear` take two clicks ([`LaneAction`]): nothing in the
/// plugin can undo either, so the second click is the whole of the safety
/// net, and it is deliberately the same button rather than a dialogue — the
/// item re-labels itself and the hand is already there.
///
/// A free function rather than a method for [`write_field`]'s reason: the
/// closure runs while [`BitstepEditor::ui_lane_header`] holds borrows of the
/// model and of the rename buffer.
fn lane_menu(
    handle: &egui::Response,
    model: &SeqModel,
    rename: &mut Option<LaneRename>,
    confirm: &mut Option<LaneConfirm>,
    rng: &mut Prng,
    target: MenuLane<'_>,
) {
    let MenuLane { lane, pattern, step_beats } = target;
    // `CloseOnClickOutside`, not the context-menu default `CloseOnClick`:
    // the default closes the menu on *any* click, inside it too, which would
    // close it as soon as the rename field is clicked and disarm `delete` /
    // `clear` before their second click. The one-shot items close it
    // themselves with `ui.close()`.
    let shown = Popup::context_menu(handle)
        .close_behavior(PopupCloseBehavior::CloseOnClickOutside)
        .show(|ui| {
        ui.set_width(LANE_MENU_WIDTH);

        // The rename field's buffer, refilled whenever the menu in front of
        // the user belongs to another lane than the last one typed into.
        let held = match rename {
            Some(held) if held.lane_id == lane.id => held,
            _ => rename.insert(LaneRename { lane_id: lane.id, text: lane.name.clone() }),
        };
        let field = ui.add(
            TextEdit::singleline(&mut held.text)
                .char_limit(LANE_NAME_LIMIT)
                .hint_text("lane name")
                .desired_width(f32::INFINITY),
        );
        // Only on a change: a name lives in the `Lane`, so a rename is a
        // *shape* edit that republishes the sequence, and a field that wrote
        // every frame it was open would do that thirty times a second for a
        // name nobody was typing.
        if field.changed() {
            model.rename_lane(lane.id, held.text.clone());
        } else if !field.has_focus() && held.text != lane.name {
            // The name moved under the buffer — a state load, the host
            // handing back a project — so the buffer follows it rather than
            // re-imposing a stale name on the next keystroke.
            held.text = lane.name.clone();
        }

        ui.separator();

        // The palette as swatches, wrapped into rows by the menu's width.
        // Stored colours are `0xRRGGBB`, so only those bits are compared: a
        // snapshot with something in the top byte must still light its swatch
        // (as [`theme::rgb`] still draws it).
        ui.horizontal_wrapped(|ui| {
            for index in 0..theme::LANE_SWATCHES.len() {
                let colour = theme::lane_swatch_rgb(index);
                let chosen = lane.colour & theme::RGB_MASK == colour;
                let swatch = Button::new("")
                    .fill(theme::lane_swatch(index))
                    .corner_radius(theme::CELL_CORNER)
                    .min_size(Vec2::splat(theme::SWATCH_SIZE))
                    .selected(chosen);
                if ui.add(swatch).clicked() {
                    model.set_colour(lane.id, colour);
                }
            }
        });

        ui.separator();

        // The MIDI channel, one-based as every host counts it
        // ([`grid_math::channel_widget`]).
        ui.horizontal(|ui| {
            ui.label("channel");
            let id = ui.next_auto_id();
            let steps = arrow_steps(ui, id);
            ui.add(
                DragValue::from_get_set(|value| {
                    if let Some(value) = value {
                        model.set_channel(lane.id, grid_math::widget_channel(value));
                    }
                    grid_math::channel_widget(lane.channel())
                })
                .speed(CHANNEL_DRAG_SPEED)
                .fixed_decimals(0)
                .range(1..=i64::from(Lane::CHANNEL_MAX) + 1),
            );
            if steps != 0 {
                let wanted = grid_math::channel_widget(lane.channel()) + f64::from(steps);
                model.set_channel(lane.id, grid_math::widget_channel(wanted));
            }
        });

        // Retunes the lane for a keytracked sample left at its default root,
        // so the pad needs no root key of its own.
        let mut sample_pad = lane.is_sample_pad();
        let toggle = ui.checkbox(&mut sample_pad, "Sample pad").on_hover_text(
            "For a sample with keytrack on and its root key at C3: plays it at its own pitch \
             on this lane's note, so the pad needs no root key. Leave off for synth drums.",
        );
        if toggle.changed() {
            model.set_sample_pad(lane.id, sample_pad);
        }

        ui.separator();

        // The shape edits. `duplicate_lane` hands back the new lane's id for
        // a GUI that wants to select it; nothing here does yet.
        if ui.button("duplicate").clicked() {
            *confirm = None;
            let _ = model.duplicate_lane(lane.id);
            ui.close();
        }
        if confirm_item(ui, confirm, lane, LaneAction::Delete) {
            model.remove_lane(lane.id);
            ui.close();
        }

        ui.separator();

        // The bulk edits, all four on the pattern *on screen* only: the grid
        // is what they are aimed at.
        if confirm_item(ui, confirm, lane, LaneAction::Clear) {
            model.clear_lane(pattern, lane.id);
            ui.close();
        }
        if ui.button("invert").clicked() {
            *confirm = None;
            model.invert_lane(pattern, lane.id);
            ui.close();
        }
        // One click, and no undo either — but a roll of the dice is meant to
        // be repeated, so the warning is in the hover rather than in a second
        // click ([`LaneAction`]).
        let roll = ui.button("randomise");
        if roll.clicked() {
            *confirm = None;
            model.randomise_lane(pattern, lane.id, RANDOMISE_DENSITY, rng);
            ui.close();
        }
        roll.on_hover_text("Rolls every step of this lane in the pattern on screen.");
        ui.horizontal(|ui| {
            ui.label("nudge");
            if ui.button("-1").clicked() {
                *confirm = None;
                model.nudge_lane(pattern, lane.id, -1);
                ui.close();
            }
            if ui.button("+1").clicked() {
                *confirm = None;
                model.nudge_lane(pattern, lane.id, 1);
                ui.close();
            }
        });

        ui.separator();

        // Preset rhythms. Like randomise, each replaces the lane's on/off
        // pattern on screen in one click, keeping the steps' values. A fill
        // that does not line up with this lane's rate is greyed out.
        ui.label("Fill");
        ui.horizontal_wrapped(|ui| {
            for fill in Fill::ALL {
                let button = ui
                    .add_enabled(fill.fits(step_beats), Button::new(fill.label()))
                    .on_hover_text(fill.hint())
                    .on_disabled_hover_text("Doesn't line up with this lane's rate");
                if button.clicked() {
                    *confirm = None;
                    model.fill_lane(pattern, lane.id, |index| fill.hits(index, step_beats));
                    ui.close();
                }
            }
        });
    });

    // The menu is shut — this frame, or every frame since it was last open.
    // An arm does not outlive it: `delete` left armed would otherwise fire on
    // the first click of the next visit, which is the very thing the second
    // click is there to prevent.
    if shown.is_none() && confirm.as_ref().is_some_and(|armed| armed.lane_id == lane.id) {
        *confirm = None;
    }
}

/// One of the two destructive menu items ([`LaneAction`]): `true` when it has
/// just been clicked for the second time and the caller should go ahead.
///
/// The first click arms it — the item re-labels itself in [`theme::WARN`] and
/// says in its hover what it is about to do — and the second performs it.
/// Arming either item disarms whatever was armed before, so the two can never
/// both be one click from firing.
fn confirm_item(
    ui: &mut egui::Ui,
    confirm: &mut Option<LaneConfirm>,
    lane: &Lane,
    action: LaneAction,
) -> bool {
    let label = if is_armed(confirm, lane.id, action) {
        RichText::new(action.armed_label()).color(theme::WARN)
    } else {
        RichText::new(action.label())
    };
    // `on_hover_text` consumes the response and hands it back, so the hover
    // is attached on the way to the click check rather than beside it.
    let item = ui.button(label).on_hover_text(action.warning());

    item.clicked() && confirm_click(confirm, lane.id, action)
}

/// Whether `action` on `lane_id` is the item that is armed right now.
fn is_armed(confirm: &Option<LaneConfirm>, lane_id: u32, action: LaneAction) -> bool {
    confirm.as_ref().is_some_and(|armed| armed.lane_id == lane_id && armed.action == action)
}

/// A click on a destructive item: `true` when it was already armed and the
/// edit should go ahead, `false` when this click only armed it.
///
/// The decision rather than the widget, so the thing standing between a
/// mis-click and a lost lane can be tested without a window
/// ([`confirm_item`] is the egui half). Arming replaces whatever was armed
/// before — one `Option` for both items and every lane, so at most one edit
/// is ever one click from firing.
fn confirm_click(confirm: &mut Option<LaneConfirm>, lane_id: u32, action: LaneAction) -> bool {
    if is_armed(confirm, lane_id, action) {
        *confirm = None;
        return true;
    }
    *confirm = Some(LaneConfirm { lane_id, action });
    false
}

/// A click on "copy to `to`" in pattern `from`'s menu: `true` when the copy
/// should go ahead now. An empty target goes on the first click; one with
/// notes is armed by the first and copied over by the second. Clicking any
/// other target re-arms rather than copies.
fn pattern_copy_click(
    armed: &mut Option<PatternCopy>,
    from: usize,
    to: usize,
    target_empty: bool,
) -> bool {
    let click = PatternCopy { from, to };
    if target_empty || *armed == Some(click) {
        *armed = None;
        return true;
    }
    *armed = Some(click);
    false
}

/// Whether no lane has a step switched on in `pattern`, hidden steps
/// included (they come back when a lane is lengthened).
fn pattern_is_empty(data: &SeqData, pattern: usize) -> bool {
    (0..data.lane_count()).all(|pos| {
        data.lane_data(pattern, pos).is_none_or(|lane_data| {
            (0..lane_data.capacity()).all(|index| !lane_data.step(index).is_on())
        })
    })
}

/// A lane row's loop length in the pattern on screen, or 0 for a row with no
/// data there — what pointer handling needs to know where a row's cells stop.
///
/// Zero is right for a missing row: `GridView::hit` then finds no cell in it
/// at all, which is what a row that is not really there should offer.
fn row_length(data: &SeqData, pattern: usize, row: usize) -> u32 {
    data.lane_data(pattern, row).map_or(0, |lane_data| lane_data.length())
}

/// Paints the window behind everything: the background, the two panels, and
/// the lines that separate them from the step strip.
fn paint_chrome(painter: &Painter, layout: &EditorLayout) {
    painter.rect_filled(layout.full(), CornerRadius::ZERO, theme::WINDOW);
    painter.rect_filled(layout.top_bar(), CornerRadius::ZERO, theme::PANEL);
    painter.rect_filled(layout.headers(), CornerRadius::ZERO, theme::PANEL);

    let line = egui::Stroke::new(theme::HAIRLINE, theme::GRID_LINE);
    let bar = layout.top_bar();
    painter.hline(bar.x_range(), bar.max.y, line);
    let song = layout.song_bar();
    if song.height() > 0.0 {
        painter.rect_filled(song, CornerRadius::ZERO, theme::PANEL);
        painter.hline(song.x_range(), song.max.y, line);
    }
    let headers = layout.headers();
    painter.vline(headers.max.x, headers.y_range(), line);
}

/// Paints the hint an instance with no lanes shows, in the middle of the step
/// strip.
///
/// In the strip rather than over the header column, because the strip is what
/// is empty and the `+ lane` button it names is above it. Painted text rather
/// than a label: there is nothing to click, and a widget would need a layout
/// in a region that has none.
fn paint_empty_hint(painter: &Painter, layout: &EditorLayout) {
    painter.text(
        layout.steps().center(),
        Align2::CENTER_CENTER,
        EMPTY_HINT,
        FontId::proportional(theme::HINT_SIZE),
        theme::TEXT_DIM,
    );
}

/// Paints a step's pan/ratchet/probability markers, for the fields that are
/// not at their default: a ratchet count as n ticks, a probability under 100%
/// as a corner dot.
///
/// Only what is not the default gets a mark: a ratchet of 1 and a probability
/// of 100% are what every step starts at, so marking them would put two
/// symbols on every cell in the grid and tell the eye nothing. Pan has no
/// marker at all — it does not change *when* the step fires, there is no
/// corner left that the velocity fill does not already speak for, and the
/// popover is where it is read.
///
/// `cell` is the whole cell, not the velocity fill: the ticks hang off its
/// top edge and the dot sits in its bottom-right corner
/// ([`grid_math::ratchet_ticks`], [`grid_math::probability_dot`]), which is
/// the one pair of places a mark reads at any velocity.
fn paint_markers(painter: &Painter, cell: Rect, step: Step) {
    if let Some(mark) = grid_math::pitch_marker(cell, step.pitch()) {
        painter.rect_filled(mark, CornerRadius::ZERO, theme::MARKER);
    }
    for tick in grid_math::ratchet_ticks(cell, step.ratchet()) {
        painter.rect_filled(tick, CornerRadius::ZERO, theme::MARKER);
    }
    if step.probability() < Step::PROBABILITY_MAX {
        let dot = grid_math::probability_dot(cell);
        painter.circle_filled(dot, theme::MARKER_DOT_RADIUS, theme::MARKER);
    }
}

/// The lines under the cells: a faint one under every lane row, and a bar
/// line every [`theme::BAR_STEPS`] columns down through all the rows. Both
/// sit in the gaps between cells, so neither covers a step.
fn paint_grid_lines(painter: &Painter, view: &GridView, data: &SeqData, pattern: usize) {
    let rows = data.lane_count();
    let Some(last) = rows.checked_sub(1) else {
        return;
    };
    let line = egui::Stroke::new(theme::HAIRLINE, theme::GRID_LINE);
    for row in view.visible_rows(rows) {
        painter.hline(view.viewport().x_range(), view.row_boundary_y(row), line);
    }
    let top = view.origin().y;
    let bottom = view.row_boundary_y(last);
    let bar = egui::Stroke::new(theme::HAIRLINE, theme::BAR_LINE);
    for step in view.visible_steps(strip_steps(data, pattern)) {
        if theme::is_bar_start(step) {
            painter.vline(view.column_boundary_x(step), egui::Rangef::new(top, bottom), bar);
        }
    }
}

/// Paints the step strip: one row per visible lane, one cell per visible step.
///
/// Only the cells inside `view`'s viewport are drawn. That is not an
/// optimisation but the thing that makes the grid work at all: a lane may hold
/// [`crate::model::MAX_STEPS`] steps, and a frame that emitted a shape for
/// each of them, times the lanes, would not finish.
///
/// `pattern` is the pattern on screen, not necessarily the one playing — see
/// [`grid_math::playhead_cell`].
fn paint_steps(
    painter: &Painter,
    view: &GridView,
    data: &SeqData,
    pattern: usize,
    playhead: &Playhead,
    mode: EditMode,
    hover: Option<GridHit>,
) {
    let any_solo = data.any_solo();
    let playing_pattern = playhead.pattern();
    paint_grid_lines(painter, view, data, pattern);

    for row in view.visible_rows(data.lane_count()) {
        // Both are `Some` for every row below `lane_count` — the shape cannot
        // change under the handle this frame holds — but a row that somehow
        // has no data is skipped rather than unwrapped: this code runs inside
        // the host.
        let (Some(lane), Some(lane_data)) = (data.lane(row), data.lane_data(pattern, row)) else {
            continue;
        };

        let colour = theme::rgb(lane.colour);
        // Mute and solo change how a lane is *drawn*, never where its
        // playhead is: a silenced lane still shows its position.
        let audible = lane_is_audible(lane, any_solo);
        let length = lane_data.length();
        let playing =
            grid_math::playhead_cell(pattern, playing_pattern, playhead.step(row), length);

        let visible = view.visible_steps(length as usize);
        for index in visible.clone() {
            let cell = view.cell_rect(row, index);
            let step = lane_data.step(index);
            if mode == EditMode::Pitch {
                let lit = playing == Some(index);
                paint_pitch_cell(painter, cell, index, step, colour, audible, lit);
                continue;
            }
            if step.is_on() {
                // Background first, then the velocity's share of the cell on
                // top of it, so the unfilled part still reads as a cell.
                painter.rect_filled(cell, theme::CELL_CORNER, theme::cell_background(index));
                let fill = grid_math::fill_rect(cell, theme::fill_fraction(step.velocity()));
                let colour = if playing == Some(index) {
                    theme::playhead_step_fill(colour, audible)
                } else {
                    theme::on_step_fill(colour, audible)
                };
                painter.rect_filled(fill, theme::CELL_CORNER, colour);
                // Over the fill, so the two never hide each other.
                paint_markers(painter, cell, step);
            } else {
                // One shape for an off step: its column's shade, outlined in
                // its lane's colour so an empty row still says whose it is.
                painter.rect(
                    cell,
                    theme::CELL_CORNER,
                    theme::cell_background(index),
                    theme::off_step_stroke(colour),
                    StrokeKind::Inside,
                );
            }
        }

        // The playhead's wash goes *over* the cells, so a lit step keeps its
        // lane colour and an unlit one still shows the beat passing. Drawn on
        // the full column pitch, gaps included, so it reads as a band rather
        // than a second cell.
        if let Some(index) = playing.filter(|index| visible.contains(index)) {
            painter.rect_filled(view.column_rect(row, index), CornerRadius::ZERO, theme::PLAYHEAD);
        }

        // The cell a click would land on, outlined over everything else.
        if let Some(GridHit::Cell { row: hovered, step }) = hover
            && hovered == row
            && visible.contains(&step)
        {
            let outline = egui::Stroke::new(theme::HAIRLINE, theme::HOVER_OUTLINE);
            let cell = view.cell_rect(row, step);
            painter.rect_stroke(cell, theme::CELL_CORNER, outline, StrokeKind::Inside);
        }

        // The handle after the last step, which drags the lane's length.
        let handle = view.end_handle_rect(row, length);
        if view.viewport().intersects(handle) {
            let colour = match hover {
                Some(GridHit::EndHandle { row: hovered }) if hovered == row => {
                    theme::END_HANDLE_HOVER
                }
                _ => theme::END_HANDLE,
            };
            painter.rect_filled(handle, theme::CELL_CORNER, colour);
        }
    }
}

/// One cell in pitch mode: the step's on/off state kept faint in the
/// background, a line through the middle (pitch 0), and the pitch as a bar
/// up or down from it with its value written on the cell.
fn paint_pitch_cell(
    painter: &Painter,
    cell: Rect,
    index: usize,
    step: Step,
    colour: egui::Color32,
    audible: bool,
    playing: bool,
) {
    let background = if step.is_on() {
        theme::dim(colour, theme::PITCH_MODE_ON_FACTOR)
    } else {
        theme::cell_background(index)
    };
    painter.rect(
        cell,
        theme::CELL_CORNER,
        background,
        theme::off_step_stroke(colour),
        StrokeKind::Inside,
    );
    let mid = cell.center().y;
    painter.hline(cell.x_range().shrink(theme::MARKER_INSET), mid, (1.0, theme::GRID_LINE));
    if let Some(bar) = grid_math::pitch_bar(cell, step.pitch()) {
        let fill = match (step.is_on(), playing) {
            (true, true) => theme::playhead_step_fill(colour, audible),
            (true, false) => theme::on_step_fill(colour, audible),
            (false, _) => theme::dim(colour, theme::MUTED_FACTOR),
        };
        painter.rect_filled(bar, CornerRadius::ZERO, fill);
        painter.text(
            cell.center(),
            Align2::CENTER_CENTER,
            grid_math::pitch_label(step.pitch()),
            FontId::proportional(theme::PITCH_LABEL_SIZE),
            theme::TEXT,
        );
    }
}

impl NiceEguiApp for BitstepEditor {
    /// Window opened: dress the context in the plugin's palette and keep the
    /// context the parameter setter needs.
    fn build(
        &mut self,
        egui_ctx: egui::Context,
        nice_gui_ctx: GuiContext,
        _frame: &mut Frame,
    ) -> Result<(), nice_plug_egui::baseview::HandlerError> {
        // Once per window: the style outlives the frame, and every widget the
        // rest of the editor adds inherits it.
        theme::apply(&egui_ctx);
        self.gui_context = Some(nice_gui_ctx);
        Ok(())
    }

    /// One frame.
    ///
    /// The window is split by [`EditorLayout`] rather than by egui panels: the
    /// step strip is one hand-painted widget whose columns have to stay in
    /// line with the lane headers, which is arithmetic
    /// ([`grid_math`]) rather than layout.
    fn ui(&mut self, ui: &mut egui::Ui, frame: &mut Frame) {
        // Before anything that could early-return: a frame that forgets this
        // is the last frame, and the playhead freezes.
        self.repaint.request_repaint();
        // Before any widget looks at this frame's keys, and undo before the
        // forwarding, which would hand Ctrl+Z to the host.
        self.handle_history(ui);
        self.forward_host_keys(ui, frame);

        // One `get()` per frame, as on the audio thread — the shape must not
        // change underneath a half-drawn grid.
        let data = self.model.shared();
        let pattern = self.shown_pattern();
        let panel = if self.panel_open { theme::PARAM_PANEL_HEIGHT } else { 0.0 };
        let song = if data.song.is_on() { theme::SONG_BAR_HEIGHT } else { 0.0 };
        let layout =
            EditorLayout::from_theme(ui.max_rect()).with_song_bar(song).with_panel(panel);
        let view = self.settle_scroll(&layout, &data, pattern);

        // Before the painting, so a step edited by this frame's press is
        // already drawn in its new state: value edits land in the `SeqData`
        // this frame is holding, not in a replacement for it.
        let hover = self.interact_steps(ui, &view, &data, pattern);

        // No panel is shown, so nothing paints the window for us.
        paint_chrome(ui.painter(), &layout);
        // Clipped to the strip: a lane longer than the window — or one the
        // scroll has moved out of it — must not draw over the headers.
        paint_steps(
            &ui.painter_at(layout.steps()),
            &view,
            &data,
            pattern,
            &self.playhead,
            self.mode,
            hover,
        );
        if data.lane_count() == 0 {
            paint_empty_hint(&ui.painter_at(layout.steps()), &layout);
        }
        self.ui_lane_headers(ui, &layout, &view, &data, pattern);
        self.ui_param_panel(ui, &layout, &data, pattern);
        self.ui_top_bar(ui, &layout, &data);
        self.ui_song_bar(ui, &layout, &data, pattern);
        // Last of the widgets, so its own layer is created above every one of
        // them and a click on a slider in it cannot fall through to the cell
        // underneath.
        self.ui_step_popover(ui, &data, pattern);

        // Last of the input handling, so every widget above has had its turn
        // at the wheel — see [`BitstepEditor::scroll_grid`].
        self.scroll_grid(ui, &layout);

        // Every frame: `shared()` above is what
        // keeps a replaced `SeqData` alive, and this is the only thread that
        // may free it. Last in the frame so it also retires the `SeqData` this
        // frame just finished with.
        drop(data);
        self.model.collect();
    }

    /// Window closed. The handles stay — the next open gets a fresh context.
    fn editor_closed(&mut self) {
        // The last gesture of the session is a step like any other.
        self.model.commit_edits();
        self.gui_context = None;
        // The next window is a new X window with a parent of its own.
        self.key_forwarder = None;
        self.key_forwarder_tried = false;
    }
}

/// Builds the editor for one plugin instance.
///
/// Separate from [`crate::Bitstep::editor`] so that it can be called without
/// an [`AsyncExecutor`], which is how the construction test gets at it without
/// a host or a display. Nothing here touches the window system;
/// `create_egui_editor` only assembles the [`Editor`] that a later
/// `Editor::spawn()` would open a window from.
///
/// `state` and `notifier` outlive the window, so they belong to the plugin
/// instance: a window reopened after a resize comes back the size the user
/// left it.
pub fn create(
    params: Arc<BitstepParams>,
    model: Arc<SeqModel>,
    playhead: Arc<Playhead>,
    state: Arc<EguiEditorState>,
    notifier: RepaintNotifier,
) -> Option<EguiEditor<BitstepEditor>> {
    let settings = EguiNiceSettings::new()
        .with_tile(crate::Bitstep::NAME)
        .with_resize_hint(ResizeHint::RESIZABLE.with_min_logical_size(MIN_SIZE))
        .with_repaint_poll_interval(REPAINT_INTERVAL);

    let mut app = BitstepEditor::new(params, model, playhead);
    app.repaint = notifier.clone();
    create_egui_editor(state, notifier, settings, app)
}

/// The window state a fresh plugin instance starts with.
///
/// Its size tracks the window's for as long as the instance lives, but it is
/// not part of the host's project state: nice-plug-egui 0.6 has no serialisable
/// form of it (an open question for now), so a reloaded project opens at
/// [`DEFAULT_SIZE`] again.
pub fn default_state() -> Arc<EguiEditorState> {
    EguiEditorState::from_size(DEFAULT_SIZE, 1.0)
}

