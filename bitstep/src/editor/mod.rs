    /// Dragging the key field moves the lane's key, and dragging the length
    /// field past the lane's capacity grows it first (see [`LengthEdit`]).
    ///
    /// The exact number of semitones or steps a drag of 40 points lands on is
    /// egui's (its drag value rounds through `smart_aim`), so this checks the
    /// direction and the range — what it is really after is that the two
    /// fields are wired to the right lane, the right pattern and the right
    /// `SeqModel` call, and that crossing the capacity is a grow rather than
    /// a silent clamp.
    #[test]
    fn dragging_the_key_and_length_fields_edits_the_lane() {
        let model = Arc::new(SeqModel::new(state::default_data()));
        let params = Arc::new(BitstepParams::new(Arc::clone(&model)));
        let mut app = BitstepEditor::new(params, Arc::clone(&model), Arc::new(Playhead::new()));

        let ctx = egui::Context::default();
        theme::apply(&ctx);

        let (pattern, row) = (0usize, 1usize);
        let key = || model.shared().lane(row).expect("lane 1 exists").key();
        let length = || model.shared().lane_data(pattern, row).expect("lane 1").length();
        let capacity = || model.shared().lane_data(pattern, row).expect("lane 1").capacity();

        // The snare, as `state::default_data` leaves it: C#1, two bars of
        // 1/16 steps, and exactly the capacity to hold them.
        assert_eq!((key(), length(), capacity()), (37, 32, 32));
        assert_eq!(grid_math::note_name(key()), "C#1");

        // Right is up: 40 points at a quarter-semitone each is about ten.
        let fields = test_header_fields(row);
        let key_field = fields.key.center();
        drag_between(&mut app, &ctx, key_field, key_field + egui::vec2(40.0, 0.0));
        let raised = key();
        assert!((40..=52).contains(&raised), "a drag right raised the key to {raised}");
        assert_eq!(model.shared().lane(0).expect("lane 0").key(), 36, "only lane 1 moved");

        // And left is down, from wherever the first drag left it.
        drag_between(&mut app, &ctx, key_field, key_field - egui::vec2(40.0, 0.0));
        assert!(key() < raised, "a drag left lowered the key to {}", key());

        // The length past the lane's capacity: the grow happens first, so the
        // length the lane ends up with is the one asked for rather than the
        // 32 a bare `set_length` would have clamped it to.
        drag_between(
            &mut app,
            &ctx,
            fields.length.center(),
            fields.length.center() + egui::vec2(40.0, 0.0),
        );
        let grown = length();
        assert!((33..=48).contains(&grown), "a drag right lengthened the lane to {grown}");
        assert!(capacity() >= grown as usize, "the lane was grown to hold its length");
        assert_eq!(capacity() % crate::model::CAPACITY_CHUNK, 0, "grown in whole chunks");

        // A grow is a shape edit, so the steps it copied across have to still
        // be there — and every other lane's content with them.
        assert_eq!(model.shared().lane_count(), 8);
        assert_eq!(model.shared().lane(row).expect("lane 1").name, "Lane 2");
        for other in [0usize, 2, 3] {
            let data = model.shared();
            let lane_data = data.lane_data(pattern, other).expect("every lane has data");
            assert_eq!(lane_data.length(), 32, "lane {other} kept its length");
            assert_eq!(lane_data.capacity(), 32, "and its capacity");
        }

        // Shorter again, which needs no shape edit at all.
        drag_between(
            &mut app,
            &ctx,
            fields.length.center(),
            fields.length.center() - egui::vec2(60.0, 0.0),
        );
        assert!(length() < grown, "a drag left shortened the lane to {}", length());
        assert!(length() >= LengthEdit::MIN, "a lane always has a step to play");

        model.collect();
    }

