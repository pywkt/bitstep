    /// Dragging the handle after a lane's last step edits its loop length,
    /// growing the lane's capacity where the drag goes past it.
    ///
    /// The dx→length arithmetic is [`grid_math`]'s and tested there; what
    /// this covers is the wiring — that a press on the handle starts the
    /// length drag rather than painting a step, that it is the handle's own
    /// lane and pattern that move, and that crossing the capacity is a grow
    /// rather than a silent clamp.
    #[test]
    fn dragging_the_end_handle_edits_the_loop_length() {
        // The hat in pattern 1 is one full capacity chunk of 16 steps, as an
        // older project saves it, so the drag below has to grow it.
        let mut data = state::default_data();
        data.patterns[0][2] = LaneData::with_capacity(crate::model::CAPACITY_CHUNK);
        let model = Arc::new(SeqModel::new(data));
        let params = Arc::new(BitstepParams::new(Arc::clone(&model)));
        let mut app = BitstepEditor::new(params, Arc::clone(&model), Arc::new(Playhead::new()));

        let layout = EditorLayout::from_theme(test_window());
        let view = layout.grid_view(CellMetrics::from_theme(), Vec2::ZERO);
        let (pattern, row) = (0usize, 2usize);
        let length = || model.shared().lane_data(pattern, row).expect("lane 2 exists").length();
        let capacity = || model.shared().lane_data(pattern, row).expect("lane 2 exists").capacity();

        assert_eq!((length(), capacity()), (16, 16));
        let pitch = view.metrics().step_pitch();
        let grip = view.end_handle_rect(row, 16).center();

        // Grabbing the handle is not an edit, and it is not a painted step
        // either — the handle wins over the cell beneath it.
        app.begin_gesture(&view, &model.shared(), pattern, grip);
        assert_eq!(length(), 16, "the press alone leaves the length alone");
        assert!(!model.shared().lane_data(pattern, row).expect("lane 2").step(15).is_on());

        // Two columns right is two steps, and the lane is grown to hold them.
        app.continue_gesture(
            &view,
            &model.shared(),
            pattern,
            grip + egui::vec2(pitch * 2.0, 0.0),
            false,
        );
        assert_eq!(length(), 18);
        assert!(capacity() >= 18, "the lane was grown to hold its length");
        assert_eq!(capacity() % crate::model::CAPACITY_CHUNK, 0, "grown in whole chunks");

        // Nothing else moved: not the lane above, not the same lane in
        // another pattern.
        let fresh = LaneData::DEFAULT_LENGTH;
        assert_eq!(model.shared().lane_data(pattern, 1).expect("lane 1").length(), fresh);
        assert_eq!(model.shared().lane_data(1, row).expect("pattern 1").length(), fresh);
        assert_eq!(model.shared().lane_count(), 8, "a grow keeps the shape");
        assert_eq!(model.shared().lane(row).expect("lane 2").name, "Lane 3");

        // The gesture reads the pointer's `x` alone, so wandering into
        // another row goes on editing the lane the press grabbed.
        let across = view.cell_rect(0, 0).center().y - grip.y;
        app.continue_gesture(
            &view,
            &model.shared(),
            pattern,
            grip + egui::vec2(pitch * 4.0, across), false,
        );
        assert_eq!(length(), 20, "the drag is locked to the handle's own lane");
        assert_eq!(model.shared().lane_data(pattern, 0).expect("lane 0").length(), fresh);

        // Dragging back restores the length the press found, and past the
        // left end it stops at the shortest loop a lane may have.
        app.continue_gesture(&view, &model.shared(), pattern, grip, false);
        assert_eq!(length(), 16, "the gesture measures from its press");
        app.continue_gesture(&view, &model.shared(), pattern, grip - egui::vec2(1e6, 0.0), false);
        assert_eq!(length(), LengthEdit::MIN);

        // Shortening needs no shape edit, so the room the grow made is still
        // there: the length is what plays, not what exists.
        assert!(capacity() >= 32, "the lane kept the capacity the drag gave it");

        // The button coming up on a length drag is not also a step toggle.
        app.end_gesture(pattern);
        assert_eq!(length(), LengthEdit::MIN);
        assert!(app.gesture.is_none());

        model.collect();
    }

    /// Follow mode scrolls the strip to the column the playhead has reached,
    /// and leaves the offset alone when it is switched off
    /// (follow keeps the playhead in view).
    ///
    /// The scroll-target arithmetic is [`GridView::follow_scroll_x`]'s and
    /// tested in [`grid_math`]; what this covers is what the editor feeds it
    /// — the playhead atomics, the pattern on screen, and the width of the
    /// content — and that the offset it settles on is one the next frame can
    /// draw through.
    #[test]
    fn follow_mode_scrolls_the_playhead_into_view() {
        let model = Arc::new(SeqModel::new(state::default_data()));
        let params = Arc::new(BitstepParams::new(Arc::clone(&model)));
        let playhead = Arc::new(Playhead::new());
        let mut app =
            BitstepEditor::new(params, Arc::clone(&model), Arc::clone(&playhead));

        let layout = EditorLayout::from_theme(test_window());
        let pattern = 0usize;
        // Two lanes long enough to need scrolling, so the strip is wider than
        // its viewport and the rightmost lit column is not the only one.
        let long = 256u32;
        for row in [0usize, 1] {
            let lane_id = model.shared().lane(row).expect("the default lanes").id;
            assert!(model.ensure_capacity(pattern, lane_id, long as usize));
            assert!(model.set_length(pattern, lane_id, long));
        }

        // Nothing playing: there is no column to follow, so the strip stays
        // where the user left it.
        let view = app.settle_scroll(&layout, &model.shared(), pattern);
        assert!(app.follow, "a fresh editor follows the playhead");
        assert_eq!(app.scroll, Vec2::ZERO);
        assert_eq!(view.scroll(), Vec2::ZERO);
        assert!(view.max_scroll_x(long as usize) > 0.0, "the strip is scrollable");

        // The transport runs: the lit column is scrolled into view, and the
        // offset is one the strip actually has.
        playhead.set_pattern(pattern as u32);
        playhead.set_step(0, 50);
        playhead.set_step(1, 200);
        let view = app.settle_scroll(&layout, &model.shared(), pattern);
        assert!(app.scroll.x > 0.0, "the strip scrolled to the playhead");
        assert_eq!(view.scroll().x, app.scroll.x, "the frame draws through the new offset");
        let visible = view.visible_steps(long as usize);
        assert!(visible.contains(&200), "the rightmost lit column is in view");
        assert!(app.scroll.x <= view.max_scroll_x(long as usize));
        assert_eq!(app.scroll.y, 0.0, "follow mode is horizontal only");

        // A pattern nobody is playing is not followed: the grid on screen is
        // `patsel`'s, which the audio thread may not have reached.
        let parked = app.scroll;
        playhead.set_pattern(1);
        app.settle_scroll(&layout, &model.shared(), pattern);
        assert_eq!(app.scroll, parked, "another pattern's playhead is not followed");

        // Switched off, the playhead moving changes nothing.
        playhead.set_pattern(pattern as u32);
        app.follow = false;
        playhead.set_step(1, 0);
        app.settle_scroll(&layout, &model.shared(), pattern);
        assert_eq!(app.scroll, parked, "a parked strip stays parked");

        // However far it was scrolled, an offset past the end of a shortened
        // lane comes back legal rather than leaving the grid blank.
        let lane_id = model.shared().lane(0).expect("lane 0").id;
        for row in 0..model.shared().lane_count() {
            let id = model.shared().lane(row).expect("the default lanes").id;
            assert!(model.set_length(pattern, id, 16));
        }
        assert_eq!(lane_id, model.shared().lane(0).expect("lane 0").id);
        let view = app.settle_scroll(&layout, &model.shared(), pattern);
        assert_eq!(app.scroll, Vec2::ZERO, "the content no longer reaches that far");
        assert!(view.visible_steps(16).contains(&0));

        model.collect();
    }

    /// The follow toggle in the top bar turns the auto-scroll on and off, and
    /// the wheel over the grid scrolls it by hand.
    #[test]
    fn the_top_bar_toggle_and_the_wheel_drive_the_scroll() {
        let model = Arc::new(SeqModel::new(state::default_data()));
        let params = Arc::new(BitstepParams::new(Arc::clone(&model)));
        let mut app = BitstepEditor::new(params, Arc::clone(&model), Arc::new(Playhead::new()));

        let ctx = egui::Context::default();
        theme::apply(&ctx);

        // A lane wide enough for the strip to have somewhere to scroll to.
        let lane_id = model.shared().lane(0).expect("lane 0").id;
        assert!(model.ensure_capacity(0, lane_id, 256));
        assert!(model.set_length(0, lane_id, 256));

        // The toggle is where the layout puts it, and a click flips it.
        let layout = EditorLayout::from_theme(test_window());
        let toggle = layout.follow_button().center();
        assert!(app.follow);
        click_at(&mut app, &ctx, toggle);
        assert!(!app.follow, "the follow toggle turned the auto-scroll off");
        click_at(&mut app, &ctx, toggle);
        assert!(app.follow, "and back on");

        // Nothing is playing, so the wheel has the offset to itself. A wheel
        // that moves the content left scrolls the strip right; how far is
        // egui's (it smooths a notch over several frames), so this checks the
        // direction and that the offset stays legal.
        app.follow = false;
        let over_grid = layout.steps().center();
        let wheel = |delta| egui::Event::MouseWheel {
            unit: egui::MouseWheelUnit::Point,
            delta,
            phase: egui::TouchPhase::Move,
            source: egui::MouseWheelSource::Unknown,
            modifiers: egui::Modifiers::default(),
        };
        run_frame(&mut app, &ctx, vec![egui::Event::PointerMoved(over_grid)]);
        assert_eq!(app.scroll, Vec2::ZERO);
        for _ in 0..8 {
            run_frame(
                &mut app,
                &ctx,
                vec![egui::Event::PointerMoved(over_grid), wheel(egui::vec2(-40.0, 0.0))],
            );
        }
        // The wheel is spent on the offset the *next* frame draws through, so
        // what the strip ends up showing is whatever the next frame settles
        // on — which is also where the offset is held inside the bounds.
        let view = app.settle_scroll(&layout, &model.shared(), 0);
        let scrolled = app.scroll.x;
        assert!(scrolled > 0.0, "the wheel scrolled the strip to {scrolled}");
        assert!(scrolled <= view.max_scroll_x(256), "and no further than the content goes");
        assert!(view.visible_steps(256).start > 0, "the first column has scrolled away");

        // The other way brings it back, and the offset never ends up left of
        // the content however long the wheel keeps turning.
        for _ in 0..40 {
            run_frame(
                &mut app,
                &ctx,
                vec![egui::Event::PointerMoved(over_grid), wheel(egui::vec2(40.0, 0.0))],
            );
        }
        let view = app.settle_scroll(&layout, &model.shared(), 0);
        assert_eq!(view.scroll(), Vec2::ZERO, "the strip is back at step 0");
        assert_eq!(app.scroll, Vec2::ZERO);

        // A wheel over the top bar is not the grid's.
        let before = app.scroll;
        assert_eq!(before, Vec2::ZERO);
        let over_bar = layout.top_bar().center();
        for _ in 0..4 {
            run_frame(
                &mut app,
                &ctx,
                vec![egui::Event::PointerMoved(over_bar), wheel(egui::vec2(-40.0, -40.0))],
            );
        }
        assert_eq!(app.scroll, before, "the top bar does not scroll the grid");

        model.collect();
    }

