/// ~30 Hz, the rate the playhead is driven at.
///
/// nice-plug-egui does not redraw on its own: a frame happens when something
/// asks for one — input, or the [`RepaintNotifier`] the adapter polls at this
/// interval. [`NiceEguiApp::ui`] raises the notifier every frame so the
/// playhead keeps moving, and so does the host side (a parameter moved by
/// automation, a state load). 30 Hz is enough for a step grid and leaves the
/// GUI thread idle between frames.
///
/// The notifier rather than `egui::Context::request_repaint_after`: on X11
/// every one of those calls starts a one-shot timer of its own, so each frame
/// drawn for input started another chain of repaints, and after a minute of
/// editing the window redrew many times faster than this. The poll timer is
/// one fixed timer, whatever the frame rate was.
pub const REPAINT_INTERVAL: Duration = Duration::from_micros(33_333);

/// Everything the editor draws from, and the GUI-only state it accumulates.
///
/// Built once per plugin instance and kept alive across window open/close —
/// nice-plug-egui calls [`NiceEguiApp::build`] again on a reopen, so anything
/// tied to a particular window (the [`GuiContext`]) is set there and dropped
/// in [`NiceEguiApp::editor_closed`].
pub struct BitstepEditor {
    /// Host parameters, read for `patsel` and written through
    /// [`Self::gui_context`]'s setter so automation records the change.
    params: Arc<BitstepParams>,
    /// The sequence. Read with one `shared()` per frame, written through the
    /// model's own setters.
    model: Arc<SeqModel>,
    /// Where playback is, as the audio thread last left it.
    playhead: Arc<Playhead>,
    /// The host-facing side of the GUI, handed over when the window opens.
    /// `None` while the editor is closed.
    gui_context: Option<GuiContext>,
    /// The pointer gesture in progress, or `None` whenever no button is down
    /// on the grid. GUI-only state: nothing outside this struct can see it,
    /// and the edits it makes are in the model the instant they happen.
    gesture: Option<Gesture>,
    /// The pattern [`Self::gesture`] was started in. A gesture only ever
    /// edits that pattern, as [`StepPopover`] does: if automation moves
    /// `patsel` mid-drag, the drag pauses until its pattern is back on screen
    /// rather than carrying on into the one now shown, and a click still
    /// toggles the step it landed on.
    gesture_pattern: usize,
    /// The step whose pan/ratchet/probability popover is open, or `None` when
    /// none is. GUI-only, like [`Self::gesture`]: the sliders in it write
    /// straight through the model, so there is no edit buffered here.
    popover: Option<StepPopover>,
    /// Wheel scroll banked over one lane's key field, or `None` when none has
    /// been scrolled yet. GUI-only, like [`Self::gesture`].
    key_scroll: Option<KeyScroll>,
    /// The lane being dragged to a new position, or `None` when none is
    /// (a lane is reordered by dragging its handle). GUI-only:
    /// each row the drag crosses is already a `move_lane` in the model.
    lane_drag: Option<LaneDrag>,
    /// The name being typed into one lane's rename field, or `None` when no
    /// lane's menu has been opened yet.
    ///
    /// The one piece of GUI state that is not already in the model: a text
    /// field needs somewhere to hold what is being typed. Every keystroke is
    /// written through, so the model is still the truth — this is the
    /// keyboard's buffer, not a pending edit.
    rename: Option<LaneRename>,
    /// The lane name being typed in place, after a double-click on the
    /// name, or `None` when no name is being edited that way ([`NameEdit`]).
    name_edit: Option<NameEdit>,
    /// The destructive menu item that has been clicked once and is waiting to
    /// be clicked again, or `None` when none is ([`LaneConfirm`]).
    confirm: Option<LaneConfirm>,
    /// A pattern copy that would replace a pattern with notes in it, clicked
    /// once and waiting for the second click ([`pattern_copy_click`]).
    pattern_copy: Option<PatternCopy>,
    /// Which page of pattern buttons the top bar shows.
    pattern_page: usize,
    /// The pattern [`Self::pattern_page`] was last moved to show. When the
    /// shown pattern changes the page follows it; the arrows move it freely
    /// in between.
    paged_for: Option<usize>,
    /// What is being typed into the song order field: the keyboard's buffer,
    /// like [`Self::rename`]. Each keystroke that reads as a song is written
    /// through at once.
    song_edit: Option<String>,
    /// How far the song row's bar cells are scrolled, in points.
    song_scroll: f32,
    /// The dice a lane's "randomise" menu item rolls.
    ///
    /// The editor's own generator, never the audio thread's: `randomise_lane`
    /// is a writer-side bulk edit, and keeping the state here is what makes
    /// repeated presses give different patterns.
    rng: Prng,
    /// How far the step strip is scrolled, in points: the offset every lane's
    /// cells are drawn through, so they stay aligned by step index and the
    /// lane headers stay on their own rows.
    ///
    /// Held here rather than in an [`egui::ScrollArea`] because the strip is
    /// one hand-painted widget whose rows the pinned headers have to line up
    /// with: one offset, read by both, is what keeps them in step. Re-clamped
    /// every frame ([`GridView::clamp_scroll`]) — the content it points into
    /// changes under it whenever a lane is shortened or removed.
    scroll: Vec2,
    /// Whether the strip scrolls itself to keep the playhead in view.
    ///
    /// On to start with: a fresh instance is more likely to be watched than
    /// edited, and the toggle is in the top bar for when it is the other way
    /// round.
    follow: bool,
    /// What a press on the grid edits: steps (on/off and velocity) or pitch.
    /// GUI-only, chosen with the top bar's mode buttons.
    mode: EditMode,
    /// The lane the parameter panel edits, by id. `None` (or a lane that has
    /// gone) means the first lane. Set by clicking a lane's name or a step.
    selected_lane: Option<u32>,
    /// Whether the parameter panel under the grid is shown.
    panel_open: bool,
    /// What the parameter panel shows and draws.
    param: ParamKind,
    /// A drawing gesture in the parameter panel, while the button is down.
    param_draw: Option<ParamStroke>,
    /// Sends Space and shortcut keys on to the host's window
    /// ([`keys`]). Connected on the first frame of each open window.
    key_forwarder: Option<KeyForwarder>,
    /// Whether this window has tried to connect [`Self::key_forwarder`], so
    /// a window with nothing to forward to does not retry every frame.
    key_forwarder_tried: bool,
    /// The adapter's repaint flag, raised every frame (see
    /// [`REPAINT_INTERVAL`]). A fresh one until [`create`] hands over the
    /// instance's, which is all a test needs.
    repaint: RepaintNotifier,
}

