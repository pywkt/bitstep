    /// Runs one frame's worth of the editor's widgets against a real
    /// [`egui::Context`].
    ///
    /// No display and no window: a context lays out and hit-tests on the CPU,
    /// which is as far into the GUI as a headless test can go.
    /// `NiceEguiApp::ui` itself cannot be called — it wants a `Frame`, which
    /// only a window produces — so this stands in for the part of it a context
    /// alone can run: the scroll settles, the headers and the top bar draw and
    /// answer the pointer, and the wheel is spent last, in that order and for
    /// the same reasons as in [`NiceEguiApp::ui`].
    ///
    /// The step grid is not painted here — it is hand-painted shapes, and a
    /// frame nobody looks at proves nothing about them — but the empty-state
    /// hint is: it is the one text the editor lays out itself instead of
    /// through a widget, so a frame with no lanes is worth running through it.
    fn run_frame(app: &mut BitstepEditor, ctx: &egui::Context, events: Vec<egui::Event>) {
        let data = app.model.shared();
        let pattern = app.shown_pattern();
        let input = egui::RawInput {
            screen_rect: Some(test_window()),
            events,
            ..Default::default()
        };

        // The root `Ui`, which is the window — the same thing
        // nice-plug-egui hands `NiceEguiApp::ui`.
        let mut output = ctx.run_ui(input, |ui| {
            app.handle_history(ui);
            let layout = test_layout(app, ui.max_rect());
            let view = app.settle_scroll(&layout, &data, pattern);
            if data.lane_count() == 0 {
                paint_empty_hint(&ui.painter_at(layout.steps()), &layout);
            }
            app.ui_lane_headers(ui, &layout, &view, &data, pattern);
            app.ui_param_panel(ui, &layout, &data, pattern);
            app.ui_top_bar(ui, &layout, &data);
            app.ui_song_bar(ui, &layout, &data, pattern);
            app.scroll_grid(ui, &layout);
        });
        // Nobody is uploading the font atlas here, and epaint panics on a
        // dropped texture delta rather than letting a real backend lose one.
        output.textures_delta.clear();

        drop(data);
        app.model.collect();
    }

    /// The layout `ui()` uses for `app`: the song row and the panel
    /// included when they are shown.
    fn test_layout(app: &BitstepEditor, window: egui::Rect) -> EditorLayout {
        let panel = if app.panel_open { theme::PARAM_PANEL_HEIGHT } else { 0.0 };
        let song = if app.model.shared().song.is_on() { theme::SONG_BAR_HEIGHT } else { 0.0 };
        EditorLayout::from_theme(window).with_song_bar(song).with_panel(panel)
    }

    /// Drawing in the parameter panel sets the selected lane's steps to the
    /// level under the pointer, on steps that are off as well as on ones
    /// (without switching them on); a right-click resets a step.
    #[test]
    fn the_parameter_panel_draws_levels_on_the_selected_lane() {
        let model = Arc::new(SeqModel::new(state::default_data()));
        let params = Arc::new(BitstepParams::new(Arc::clone(&model)));
        let mut app = BitstepEditor::new(params, Arc::clone(&model), Arc::new(Playhead::new()));
        let ctx = egui::Context::default();
        theme::apply(&ctx);

        let pattern = 0usize;
        let row = 1usize;
        let lane_id = model.shared().lane(row).expect("lane 1").id;
        let step = |index: usize| model.shared().lane_data(pattern, row).expect("lane").step(index);
        for index in 0..16 {
            model.set_step(pattern, lane_id, index, Step::OFF);
        }
        for index in 0..4 {
            assert!(model.set_step(pattern, lane_id, index, Step::default_on()));
        }
        app.selected_lane = Some(lane_id);

        let layout = test_layout(&app, test_window());
        let view = layout.panel_view(CellMetrics::from_theme(), 0.0);
        let plot = layout.panel_strip().shrink2(egui::vec2(0.0, theme::PARAM_PLOT_INSET));
        let column = |index: usize| view.cell_rect(0, index).center().x;

        // From step 0 at the top of the panel across to step 5: all six go to
        // full velocity, and the two that are off stay off.
        let top = plot.min.y;
        drag_between(&mut app, &ctx, egui::pos2(column(0), top), egui::pos2(column(5), top));
        let velocities: Vec<u8> = (0..6).map(|i| step(i).velocity()).collect();
        assert_eq!(velocities, [127; 6]);
        assert!(!step(4).is_on() && !step(5).is_on(), "drawing never turns steps on");
        // The empty step got the defaults under the drawn velocity, so it
        // plays as drawn once switched on rather than with a 0% chance.
        assert_eq!(step(4).probability(), Step::PROBABILITY_MAX);
        assert_eq!(step(4).turned_on().velocity(), 127);

        // A right-click resets one step to the default.
        let at = egui::pos2(column(2), top);
        let button = |pressed| egui::Event::PointerButton {
            pos: at,
            button: PointerButton::Secondary,
            pressed,
            modifiers: egui::Modifiers::default(),
        };
        run_frame(&mut app, &ctx, vec![egui::Event::PointerMoved(at)]);
        run_frame(&mut app, &ctx, vec![egui::Event::PointerMoved(at), button(true)]);
        run_frame(&mut app, &ctx, vec![button(false)]);
        assert_eq!(step(2).velocity(), 100);
        assert_eq!(step(1).velocity(), 127, "only the clicked step");

        // Pitch, as its button would select. The bottom of the panel is -24.
        app.param = ParamKind::Pitch;
        let bottom = plot.max.y - 1.0;
        drag_between(&mut app, &ctx, egui::pos2(column(3), bottom), egui::pos2(column(5), bottom));
        let pitches: Vec<i8> = (3..=5).map(|i| step(i).pitch()).collect();
        assert_eq!(pitches, [-24; 3]);
        assert!(!step(5).is_on());

        // Another lane's steps were not touched.
        let other = model.shared().lane_data(pattern, 0).expect("lane 0").step(0);
        assert_eq!(other.pitch(), 0);
    }

