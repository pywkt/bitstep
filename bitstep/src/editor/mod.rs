        app.begin_gesture(&view, &model.shared(), pattern, view.cell_rect(row, 2).center());
        app.end_gesture(pattern);
        assert_eq!(step(2).pitch(), 0, "a click resets pitch");
        assert_eq!(step(3).pitch(), 5, "and only on the clicked step");

